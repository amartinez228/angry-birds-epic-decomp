"""Recover the shipped per-level XP costs used by PlayerGameData.

OnExperienceChanged compares current-level residual XP with Experience;
ApplyLevelUp subtracts that cost and increments the level. Reward wire data is
retained separately; importing thresholds does not implement reward loot.
"""
import hashlib
import json

from recover_content import ROOT, describe, load_tables, one, signed_integer


def recover():
    tables, _ = load_tables()
    rows = []
    for raw in tables['ExperienceLevelBalancingData']:
        identifier = one(raw, 1).decode()
        level = int(identifier.removeprefix('Level_'))
        cost = signed_integer(raw, 2)
        if identifier != f'Level_{level:02}' or cost <= 0:
            raise ValueError('Invalid XP level/cost')
        rows.append(dict(id=identifier, level=level, next_level_cost=cost,
                         row_sha256=hashlib.sha256(raw).hexdigest(), raw_fields=describe(raw)))
    rows.sort(key=lambda row:row['level'])
    if [row['level'] for row in rows] != list(range(1, 100)):
        raise ValueError('Expected complete original Level_01 through Level_99 costs')
    result = dict(source_sha256=hashlib.sha256((ROOT/'analysis/unity/balancing.pb').read_bytes()).hexdigest(),
                  levels=rows, terminal_level=100,
                  limitations=['Native XP is floating point; current battle XP grants and storage use whole points',
                      'Original defeat XP/battle bonuses and initial live stat refresh are implemented; boosters, level-up loot and complete native callback/visual timing remain unfinished',
                      'One level transition per XP event follows the traced callback; complete surplus-XP/UI event choreography needs comparison'])
    (ROOT/'content/progression.json').write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
    text = '// Generated by tools/recover_progression.py.\npub const EXPERIENCE_COSTS: &[u32; 99] = &['
    text += ', '.join(str(row['next_level_cost']) for row in rows)+'];\npub const MAX_LEVEL: u32 = 100;\n'
    (ROOT/'crates/epic-core/src/progression_generated.rs').write_text(text, encoding='utf-8')
    print('Recovered',len(rows),'per-level XP costs; terminal level',result['terminal_level'])


if __name__ == '__main__':
    recover()
