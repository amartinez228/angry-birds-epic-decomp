"""Build Rust resource identities from the committed recovery manifest.

Unlike recovery, this step needs no original APK or analysis caches.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'crates/epic-core/src/resources_generated.rs'


def generate():
    source = (ROOT / 'content/resources.json').read_bytes()
    manifest = json.loads(source)
    definitions = manifest['definitions']
    localization_source = (ROOT / 'content/localization.en.json').read_bytes()
    localization = json.loads(localization_source)
    by_id = {row['id']: row for row in definitions}
    ids = [row['id'] for row in definitions]
    if len(set(ids)) != len(ids) or ids != sorted(ids):
        raise ValueError('Resource identities must be unique and sorted')
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [
        '// Generated by tools/build_resource_runtime.py; do not edit.',
        '// Manifest SHA256: ' + hashlib.sha256(source).hexdigest(),
        '// Localization SHA256: ' + hashlib.sha256(localization_source).hexdigest(),
        '#[rustfmt::skip]',
        'pub static DEFINITIONS: &[ResourceDefinition] = &[',
    ]
    for row in definitions:
        if any(char in row['id'] for char in ':,=\n\r'):
            raise ValueError('Resource ID cannot be serialized')
        # Keep recovered names separate from UI labels. Recipe labels name the
        # serialized field-6 product; missing localization uses readable words.
        label = row['name'] or row['id'].replace('_', ' ').capitalize()
        if row['item_type'] == 12:
            products = [field for field in row['raw_fields'] if field['field'] == 6]
            if len(products) == 1:
                product = next(field['text'] for field in products[0]['message'] if field['field'] == 1)
                name = by_id.get(product, {}).get('name') or localization.get(product + '_crafting_name', '')
                if name:
                    label = name
            label = 'Recipe: ' + label
        label = re.sub(r'<[^>]*>|\[[^\]]*\]', '', label).strip()
        lines.append('    ResourceDefinition { id: %s, name: %s, label: %s, item_type: %d },' % (
            quote(row['id']), quote(row['name']), quote(label), row['item_type']))
    lines += ['];', '#[rustfmt::skip]', 'pub static INITIAL: &[(&str, u32, i32)] = &[']
    for identifier, entry in sorted(manifest['initial_inventory'].items()):
        if identifier not in ids or not 0 <= entry['value'] <= 0xffffffff:
            raise ValueError('Invalid initial resource')
        lines.append('    (%s, %d, %d),' % (
            quote(identifier), entry['value'], entry['level_delta']))
    lines += ['];', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != expected:
            raise SystemExit('Stale resource runtime; run tools/build_resource_runtime.py')
        print('Resource runtime matches committed recovery manifest')
    else:
        OUTPUT.write_text(expected, encoding='utf-8')


if __name__ == '__main__':
    main()
