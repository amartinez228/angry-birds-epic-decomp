"""Recover bundled revive requirements; native behavior is traced separately."""
import hashlib
import json
import struct

from recover_content import ROOT, load_tables, one


def recover():
    tables, _ = load_tables()
    requirements = []
    for raw in tables['GameConstantsBalancingData']:
        identifier = one(raw, 1).decode()
        if identifier not in ['ReviveSingleBirdsRequirement', 'ReviveBirdsRequirement', 'ReviveBirdsPvpRequirement']:
            continue
        requirement = one(raw, 4)
        amount = struct.unpack('<f', one(requirement, 3))[0]
        if one(requirement, 1) != 1 or one(requirement, 2) != b'lucky_coin' or not amount.is_integer() or amount <= 0:
            raise ValueError('Unsupported revive resource requirement')
        requirements.append(dict(id=identifier, resource='lucky_coin', amount=int(amount),
                                 row_sha256=hashlib.sha256(raw).hexdigest()))
    if len(requirements) != 3:
        raise ValueError('Incomplete revive requirements')
    result = dict(requirements=requirements,
                  source_sha256=hashlib.sha256((ROOT/'analysis/unity/balancing.pb').read_bytes()).hexdigest(),
                  runtime=['Single-bird revival spends five coins from the recreation shared gold wallet',
                           'Native ReviveBird requests 100 percent health and rearms KnockOutOnDefeat',
                           'First full-party revive is free; subsequent non-PvP party revives cost ten coins, preserving the player entitlement flag'],
                  limitations=['Original separate currency inventory, PvP revive execution, original popup/timer, full initiative/trigger/consumable/perk flow remain unfinished'])
    (ROOT/'content/revival.json').write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
    single = next(row for row in requirements if row['id'] == 'ReviveSingleBirdsRequirement')
    names = {'ReviveSingleBirdsRequirement':'SINGLE_BIRD_COST', 'ReviveBirdsRequirement':'PARTY_COST', 'ReviveBirdsPvpRequirement':'PVP_PARTY_COST'}
    (ROOT/'crates/epic-core/src/revival_generated.rs').write_text(
        '// Generated by tools/recover_revival.py.\n'+''.join(f'pub const {names[row["id"]]}: u32 = {row["amount"]};\n' for row in requirements), encoding='utf-8')
    print('Recovered all three revive requirements; single-bird cost', single['amount'])


if __name__ == '__main__':
    recover()
