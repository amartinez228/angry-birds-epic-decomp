"""Recover result-star widgets and selected original animation channels.

--bundle needs the separate UnityPy/Pillow environment. --check needs stdlib.
Source evidence is Unity6 visual reference, not original Unity5.6 native logic.
"""
import argparse
import json
import math
import struct
from pathlib import Path

from recover_reference_layouts import BUNDLE_SHA, REVISION, sha
from recover_reference_ui import atlas_sprites
from recover_ui_motion import literal

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'content/victory-stars.json'
GENERATED = ROOT / 'crates/epic-client/src/victory_stars_generated.rs'
IMAGE = ROOT / 'assets/ui/victory_atlas.png'
WIDGETS = [(1005, 'Left'), (833, 'Center'), (827, 'Right')]
CHANNELS = [('enter_x', 4, 'm_ScaleCurves', '2_ScoreStars', 'x'),
            ('enter_y', 4, 'm_ScaleCurves', '2_ScoreStars', 'y'),
            ('gain_x', 16, 'm_ScaleCurves', '', 'x'),
            ('gain_y', 16, 'm_ScaleCurves', '', 'y'),
            ('saturation', 16, 'm_FloatCurves', 'Star', ''),
            ('header_x', 4, 'm_PositionCurves', '1_Header/Animation', 'x'),
            ('header_y', 4, 'm_PositionCurves', '1_Header/Animation', 'y'),
            ('header_scale_x', 4, 'm_ScaleCurves', '1_Header/Animation', 'x'),
            ('header_scale_y', 4, 'm_ScaleCurves', '1_Header/Animation', 'y'),
            ('header_alpha', 4, 'm_FloatCurves', '1_Header/Animation/Header', ''),
            ('score_alpha', 4, 'm_FloatCurves', '3_Score/Score', '')]


def rust_source(m):
    lines = ['// Generated by tools/recover_victory_stars.py; do not edit.',
             'const ATLAS: &[u8] = include_bytes!("../../../assets/ui/victory_atlas.png");',
             '#[rustfmt::skip]', 'static STARS: &[Star] = &[']
    for w in m['widgets']:
        rects = [next(s['rect'] for s in m['sprites'] if s['name'] == w['name'] + suffix)
                 for suffix in ['', '_Desaturated']]
        groups = [w['outer_position'][:2], w['position'][:2], w['size'], *rects]
        fields = ['outer', 'inner', 'size', 'colored', 'desaturated']
        lines.append('    Star { ' + ', '.join('%s: [%s]' % (field, ', '.join(literal(v) for v in values))
                                              for field, values in zip(fields, groups)) + ' },')
    lines.append('];')
    for c in m['channels']:
        lines += ['#[allow(clippy::excessive_precision)]', '#[rustfmt::skip]',
                  'const %s: &[[f32; 4]] = &[%s];' % (c['key'].upper(),
                    ', '.join('[' + ', '.join(literal(v) for v in k) + ']' for k in c['keys']))]
    return '\n'.join(lines + [''])


def recover(path):
    import UnityPy
    from PIL import Image
    data = Path(path).read_bytes()
    if sha(data) != BUNDLE_SHA:
        raise ValueError('Unexpected reference bundle')
    objects = {(o.assets_file.name, o.path_id): o for o in UnityPy.load(data).objects}
    atlas = objects['resources.assets', 43932]
    material_id, sprites = atlas_sprites(atlas.get_raw_data())
    material = objects['resources.assets', material_id].read()
    texture = dict(material.m_SavedProperties.m_TexEnvs)['_MainTex'].m_Texture.deref()
    source = texture.read().image
    widgets, outputs = [], []
    packed = Image.new('RGBA', (1024, 512))
    sx, sy, shelf = 2, 2, 0
    def vec(v): return [getattr(v, a) for a in 'xyz']
    def evidence(o): return dict(file=o.assets_file.name, id=o.path_id,
                                 serialized_hex=o.get_raw_data().hex(), raw_sha256=sha(o.get_raw_data()))
    for identifier, part in WIDGETS:
        obj = objects['level11', identifier]
        raw = obj.get_raw_data()
        name = 'ResultStar_' + part
        length, = struct.unpack_from('<I', raw, 264)
        if raw[268:268+length].decode() != name + '_Desaturated':
            raise ValueError('Unexpected widget sprite')
        pivot, width, height, _ = struct.unpack_from('<4i', raw, 132)
        # These widgets link via external file2 to BattleElements43932.
        fid, aid = struct.unpack_from('<iq', raw, 252)
        if pivot != 4 or aid != 43932 or obj.assets_file.externals[fid-1].path.split('/')[-1] != 'resources.assets':
            raise ValueError('Unexpected widget atlas/pivot')
        go = objects['level11', struct.unpack_from('<q', raw, 4)[0]].read()
        t_obj, = [p.component.deref() for p in go.m_Component if p.component.deref().type.name == 'Transform']
        t = t_obj.read(); outer_obj = t.m_Father.deref(); outer = outer_obj.read()
        if vec(t.m_LocalScale) != [1., 1., 1.] or vec(outer.m_LocalScale) != [1., 1., 1.]:
            raise ValueError('Unexpected local star scale')
        widgets.append(dict(name=name, size=[width,height], position=vec(t.m_LocalPosition),
                            outer_position=vec(outer.m_LocalPosition), widget=evidence(obj),
                            transform=evidence(t_obj), outer_transform=evidence(outer_obj)))
        for suffix in ['', '_Desaturated']:
            sprite_name = name + suffix
            x,y,w,h = sprites[sprite_name]['rect']
            if [w,h] != [width,height] or min(x,y)<0 or x+w>source.width or y+h>source.height:
                raise ValueError('Unexpected crop bounds/dimensions')
            crop=source.crop((x,y,x+w,y+h))
            if sx+w+2>1024: sx,sy,shelf=2,sy+shelf+4,0
            if sy+h+2>512: raise ValueError('Atlas overflow')
            # Two-pixel edge extrusion, including corners.
            for dy in range(-2,h+2):
                yy=min(max(dy,0),h-1)
                packed.paste(crop.crop((0,yy,w,yy+1)),(sx,sy+dy))
                for dx in [-2,-1,w,w+1]:
                    packed.putpixel((sx+dx,sy+dy),crop.getpixel((min(max(dx,0),w-1),yy)))
            outputs.append(dict(name=sprite_name, source_rect=[x,y,w,h], source_rgba_sha256=sha(crop.tobytes()), rect=[sx,sy,w,h]))
            sx,shelf=sx+w+4,max(shelf,h)
    channels=[]
    for key,identifier,category,path,axis in CHANNELS:
        obj=objects['sharedassets11.assets',identifier];tree=obj.read_typetree()
        curve,=[c for c in tree[category] if c['path']==path]
        if not axis and curve['attribute'] != ('_Saturation' if key == 'saturation' else 'mColor.a'):
            raise ValueError('Unexpected float channel')
        keys=[]
        for k in curve['curve']['m_Curve']:
            if k.get('weightedMode',0):raise ValueError('Weighted curve unsupported')
            values=[k['time']]+[k[f][axis] if axis else k[f] for f in ['value','inSlope','outSlope']]
            if not all(math.isfinite(v) for v in values):raise ValueError('Nonfinite star curve')
            keys.append(values)
        channels.append(dict(key=key, clip_name=tree['m_Name'], category=category,path=path,axis=axis,
                             source=evidence(obj),keys=keys))
    packed.save(IMAGE)
    m=dict(reference='https://github.com/DarkTerraYT/EpicWeb',revision=REVISION,bundle_sha256=BUNDLE_SHA,
           atlas=evidence(atlas),texture_id=texture.path_id,texture_raw_sha256=sha(texture.get_raw_data()),
           widgets=widgets,sprites=outputs,channels=channels,
           image=dict(path=IMAGE.relative_to(ROOT).as_posix(),size=[1024,512],sha256=sha(IMAGE.read_bytes())),
           limitations=['Victory parchment and overall position/scale are adapted, not original full popup layout',
                        'Gain triggers: renderer schedules left-to-right from0.75s with0.25s staggering; native callback order/delays unverified',
                        'Original saturation curve blends colored/desaturated artwork; original material shader equivalence unverified',
                        'Original header/score fade channels play in adapted parchment/font/position; header translation scaled0.65 with star layout',
                        'Score counting, effects, sounds, full victory and reward transitions remain unfinished'])
    MANIFEST.write_text(json.dumps(m,indent=2,allow_nan=False)+'\n')
    GENERATED.write_text(rust_source(m));check()


def check():
    m=json.loads(MANIFEST.read_text())
    if m['revision']!=REVISION or m['bundle_sha256']!=BUNDLE_SHA:raise ValueError('Unexpected source')
    if [w['widget']['id'] for w in m['widgets']] != [w[0] for w in WIDGETS]:raise ValueError('Changed widgets')
    if [c['key'] for c in m['channels']] != [c[0] for c in CHANNELS]:raise ValueError('Changed channels')
    for row in [m['atlas'],*[w[f] for w in m['widgets'] for f in ['widget','transform','outer_transform']],
                *[c['source'] for c in m['channels']]]:
        if sha(bytes.fromhex(row['serialized_hex'])) != row['raw_sha256']:raise ValueError('Changed source evidence')
    for c in m['channels']:
        times=[k[0] for k in c['keys']]
        if not times or times!=sorted(set(times)) or not all(len(k)==4 and all(math.isfinite(v) for v in k) for k in c['keys']):
            raise ValueError('Invalid curve')
    for s in m['sprites']:
        x,y,w,h=s['rect']
        if min(x,y)<2 or min(w,h)<=0 or x+w+2>1024 or y+h+2>512:raise ValueError('Invalid packed bounds')
    data=IMAGE.read_bytes()
    if sha(data)!=m['image']['sha256'] or data[:8]!=b'\x89PNG\r\n\x1a\n' or list(struct.unpack_from('>II',data,16))!=[1024,512]:
        raise ValueError('Changed PNG')
    if GENERATED.read_text()!=rust_source(m):raise ValueError('Stale generated Rust')
    print('Victory stars: six sprites, three widgets, eleven original channels and prepared outputs match')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    mode=parser.add_mutually_exclusive_group(required=True);mode.add_argument('--bundle');mode.add_argument('--check',action='store_true')
    args=parser.parse_args();check() if args.check else recover(args.bundle)
