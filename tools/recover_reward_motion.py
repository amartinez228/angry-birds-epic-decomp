"""Recover selected reward-wheel animation channels from pinned EpicWeb.

--bundle requires UnityPy; --check uses stdlib. Trigger scheduling and spin
rotation are renderer policy, not recovered native controller behavior.
"""
import argparse
import json
import math
from pathlib import Path
from recover_reference_layouts import BUNDLE_SHA, REVISION, sha
from recover_ui_motion import literal

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'content/reward-motion.json'
GENERATED = ROOT / 'crates/epic-client/src/reward_motion_generated.rs'
CLIPS = [('enter', 6), ('leave', 7), ('spin_start', 22), ('spin_end', 18)]


def rust_source(m):
    lines = ['// Generated by tools/recover_reward_motion.py; do not edit.',
             '#[allow(clippy::excessive_precision)]', '#[rustfmt::skip]',
             'static CURVES: &[Curve] = &[']
    for clip in m['clips']:
        for c in clip['curves']:
            keys = ', '.join('[' + ', '.join(literal(v) for v in k) + ']' for k in c['keys'])
            lines.append('    Curve { clip: %s, path: %s, property: %s, keys: &[%s] },' % (
                json.dumps(clip['key']), json.dumps(c['path']), json.dumps(c['property']), keys))
    return '\n'.join(lines + ['];', ''])


def recover(path):
    import UnityPy
    data = Path(path).read_bytes()
    if sha(data) != BUNDLE_SHA: raise ValueError('Unexpected bundle')
    objects = {(o.assets_file.name,o.path_id):o for o in UnityPy.load(data).objects}
    clips = []
    for key, identifier in CLIPS:
        obj = objects['sharedassets11.assets',identifier]
        tree = obj.read_typetree();curves=[]
        # Header channels are retained as evidence only: the current receipt's
        # heading uses an adapted layout and does not execute those channels.
        for category,prop,axes in [('m_PositionCurves','position','xy'),('m_ScaleCurves','scale','xy'),('m_FloatCurves','','')]:
            for c in tree[category]:
                for axis in axes or ['']:
                    keys=[]
                    for k in c['curve']['m_Curve']:
                        if k.get('weightedMode',0): raise ValueError('Unsupported weighted curve')
                        values=[k['time']]+[k[f][axis] if axis else k[f] for f in ['value','inSlope','outSlope']]
                        if not all(math.isfinite(v) for v in values):raise ValueError('Nonfinite curve')
                        keys.append(values)
                    curves.append(dict(path=c['path'],property=prop+'.'+axis if axis else c['attribute'],keys=keys))
        clips.append(dict(key=key,name=tree['m_Name'],file=obj.assets_file.name,id=identifier,
                          serialized_hex=obj.get_raw_data().hex(),raw_sha256=sha(obj.get_raw_data()),
                          events=tree['m_Events'],curves=curves))
    m=dict(reference='https://github.com/DarkTerraYT/EpicWeb',revision=REVISION,bundle_sha256=BUNDLE_SHA,clips=clips,
           limitations=['Original wheel enter/leave and spin alpha channels; header channels retained but not applied to adapted receipt header',
                        'Renderer starts provisional1.4second spin after wheel entrance, overlaps spin-end alpha with final0.375seconds',
                        'Continue waits for entry/spin settlement then runs wheel leave before routing to camp; native trigger/callback order unverified',
                        'Claims remain atomic before receipt display; original victory leave/whole scene transition, effects and sounds remain unfinished'])
    MANIFEST.write_text(json.dumps(m,indent=2,allow_nan=False)+'\n')
    GENERATED.write_text(rust_source(m));check()


def check():
    m=json.loads(MANIFEST.read_text())
    if m['revision']!=REVISION or m['bundle_sha256']!=BUNDLE_SHA:raise ValueError('Unexpected source')
    if [(c['key'],c['id']) for c in m['clips']]!=CLIPS:raise ValueError('Changed clip selection')
    for clip in m['clips']:
        if sha(bytes.fromhex(clip['serialized_hex']))!=clip['raw_sha256']:raise ValueError('Changed clip evidence')
        for c in clip['curves']:
            times=[k[0] for k in c['keys']]
            if not times or times!=sorted(set(times)) or not all(len(k)==4 and all(math.isfinite(v) for v in k) for k in c['keys']):
                raise ValueError('Invalid curve')
    if GENERATED.read_text()!=rust_source(m):raise ValueError('Stale generated Rust')
    print('Reward motion: four clips,',sum(len(c['curves']) for c in m['clips']),'channels match source evidence and generated Rust')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    mode=parser.add_mutually_exclusive_group(required=True);mode.add_argument('--bundle');mode.add_argument('--check',action='store_true')
    args=parser.parse_args();check() if args.check else recover(args.bundle)
