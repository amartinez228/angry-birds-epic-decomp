"""Recover original loot graphs, campaign defeat roots and XP scaling.

Native selection semantics, including consecutive wheel slots, are in loot.rs.
Live wheel UI/reward application and Unity global RNG remain unfinished.
"""
import hashlib
import json
import math
import struct

from recover_content import ROOT, describe, fields, load_tables, one, signed_integer


def entry(row):
    expected = {1:2, 2:0, 3:0, 4:5, 5:0, 6:0, 7:0}
    if any(expected.get(field) != wire for field, wire, _ in fields(row)):
        raise ValueError('Unsupported LootTableEntry field/wire')
    weight = struct.unpack('<f', one(row, 4, b'\0'*4))[0]
    if not math.isfinite(weight) or weight < 0:
        raise ValueError('Invalid loot probability/weight')
    return dict(id=one(row, 1).decode(), level_min=signed_integer(row, 2), level_max=signed_integer(row, 3),
                probability=weight, base_value=signed_integer(row, 5), span=signed_integer(row, 6),
                level_delta=signed_integer(row, 7), row_sha256=hashlib.sha256(row).hexdigest())


def recover():
    tables, _ = load_tables()
    loot = []
    for row in tables['LootTableBalancingData']:
        loot.append(dict(id=one(row, 1).decode(), kind=one(row, 3, 0),
            entries=[entry(payload) for field, wire, payload in fields(row) if field == 2 and wire == 2],
            row_sha256=hashlib.sha256(row).hexdigest()))
    if len({item['id'] for item in loot}) != len(loot):
        raise ValueError('Duplicate loot table ID')
    original_pigs = {one(row, 1).decode():row for row in tables['PigBalancingData']}
    campaign = json.loads((ROOT/'content/campaign.json').read_text())
    pigs = []
    for pig in campaign['pigs']:
        raw = original_pigs[pig['id']]
        roots = []
        for field, wire, row in fields(raw):
            if field == 13:
                if wire != 2:
                    raise ValueError('Unexpected pig defeat-loot wire')
                roots.append(dict(id=one(row, 1).decode(), amount=signed_integer(row, 2)))
        pigs.append(dict(id=pig['id'], roots=roots, row_sha256=hashlib.sha256(raw).hexdigest()))
    original_battles = {one(row, 1).decode():row for row in tables['BattleBalancingData']}
    battles = []
    for encounter in campaign['encounters']:
        raw = original_battles[encounter['battle_id']]
        def resource_map(number):
            return [dict(id=one(row, 1).decode(), amount=signed_integer(row, 2))
                    for field, wire, row in fields(raw) if field == number and wire == 2]
        battles.append(dict(id=encounter['battle_id'], wheel=resource_map(4), additional=resource_map(5), bonus=resource_map(25),
                            row_sha256=hashlib.sha256(raw).hexdigest()))
    scaling = []
    for row in tables['ExperienceScalingBalancingData']:
        difference = struct.unpack('<f', one(row, 2, b'\0'*4))[0]
        modifier = struct.unpack('<f', one(row, 3, b'\0'*4))[0]
        if not math.isfinite(difference) or not math.isfinite(modifier):
            raise ValueError('Invalid XP scaling')
        scaling.append(dict(id=one(row, 1).decode(), difference=difference, xp_percent=modifier,
                            row_sha256=hashlib.sha256(row).hexdigest()))
    scaling.sort(key=lambda row:row['difference'])
    by_id = {row['id']:row for row in loot}
    reachable = set()
    def visit(identifier):
        if identifier not in by_id or identifier in reachable:
            return
        reachable.add(identifier)
        for item in by_id[identifier]['entries']:
            visit(item['id'])
    for pig in pigs:
        for root in pig['roots']:
            visit(root['id'])
    unsupported = sorted(key for key in reachable if by_id[key]['kind'] in (3, 4))
    result = dict(source_sha256=hashlib.sha256((ROOT/'analysis/unity/balancing.pb').read_bytes()).hexdigest(),
                  tables=loot, pigs=pigs, battles=battles, xp_scaling=scaling, campaign_reachable_tables=sorted(reachable),
                  campaign_unsupported_wheel_tables=unsupported,
                  limitations=['Wheel selection/forced start implemented; live wheel UI/reward delivery and preview paths remain unfinished',
                      'Campaign XP is delivered once per defeated pig at action boundaries; original gold/mastery samples are retained in battle drops but not applied to a native inventory',
                      'Unity RNG implementation/global ordering, live modifiers, exact kill/callback order, level-up visual timing/temporary-health and perk stages, non-XP persistence and original loot UI remain unfinished'])
    (ROOT/'content/loot.json').write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
    q = json.dumps
    source = ['// Generated by tools/recover_loot.py.', 'pub const TABLES: &[LootTable] = &[']
    for table in loot:
        source.append(f'    LootTable {{ id: {q(table["id"])}, kind: {table["kind"]}, entries: &[')
        for item in table['entries']:
            source.append('        LootEntry { '+', '.join(f'{key}: '+(q(item[key]) if key == 'id' else repr(item[key]))
                for key in ['id','level_min','level_max','probability','base_value','span','level_delta'])+' },')
        source.append('    ] },')
    source.extend(['];', 'pub const PIG_DEFEAT_LOOT: &[PigDefeatLoot] = &['])
    for pig in pigs:
        roots = ', '.join(f'({q(row["id"])}, {row["amount"]})' for row in pig['roots'])
        source.append(f'    PigDefeatLoot {{ id: {q(pig["id"])}, roots: &[{roots}] }},')
    source.extend(['];', 'pub const BATTLE_LOOT: &[BattleLoot] = &['])
    for battle in battles:
        maps = {key:', '.join(f'({q(row["id"])}, {row["amount"]})' for row in battle[key]) for key in ['wheel','additional','bonus']}
        source.append(f'    BattleLoot {{ id: {q(battle["id"])}, wheel: &[{maps["wheel"]}], additional: &[{maps["additional"]}], bonus: &[{maps["bonus"]}] }},')
    source.extend(['];', 'pub const XP_SCALING: &[(f32, f32)] = &['+', '.join(f'({row["difference"]!r}, {row["xp_percent"]!r})' for row in scaling)+'];', ''])
    (ROOT/'crates/epic-core/src/loot_generated.rs').write_text('\n'.join(source), encoding='utf-8')
    print('Recovered',len(loot),'loot tables;',sum(len(t['entries']) for t in loot),'entries;',len(pigs),'pig roots;',
          len(reachable),'campaign-reachable tables;',len(unsupported),'reachable wheel tables')


if __name__ == '__main__':
    recover()
