"""Pack recovered scene rest geometry with original UVs, colors and depth.

Static batch vertices already use world space when no static root is supplied.
Runtime projects the original orthographic camera; script adjustments, shaders,
particles, dynamic sprite generation and animated scenery remain pending.
"""
import hashlib
import json
import math
import struct

from recover_art import ROOT


def point(matrix, xyz):
    return [sum(matrix[row*4+k]*xyz[k] for k in range(3))+matrix[row*4+3] for row in range(3)]


def batches(scene, data, texture_indices):
    result = []
    skipped = []
    for layer in scene['layers']:
        if layer['status'] != 'decoded':
            skipped.append(dict(path_id=layer['path_id'], reason=layer['status']))
            continue
        if not layer['enabled'] or not layer['active_in_hierarchy']:
            continue
        mesh = data['meshes'][layer['mesh_key']]
        first, size = layer['static_batch']
        submeshes = mesh['submeshes'][first:first+size] if size else mesh['submeshes']
        if len(submeshes) != len(layer['material_keys']):
            raise ValueError('Scenery material/submesh count mismatch')
        if size and layer['static_root'][1]:
            raise ValueError('Static batch root needs separate transform recovery')
        for submesh, mat_key in zip(submeshes, layer['material_keys']):
            if mat_key is None:
                skipped.append(dict(path_id=layer['path_id'], reason='null_material'))
                continue
            material = data['materials'][mat_key]
            tex_index = texture_indices.get(material.get('texture_key'), 65535)
            main = material['textures'].get('_MainTex', dict(scale=[1., 1.], offset=[0., 0.]))
            tint = material['colors'].get('_Color', [1., 1., 1., 1.])
            indices, vertices, depths, remap = [], [], [], {}
            for original in submesh['indices']:
                if original not in remap:
                    remap[original] = len(vertices)
                    xyz = mesh['positions'][original]
                    if not size:
                        xyz = point(layer['world_matrix'], xyz)
                    u, v = mesh['uvs'][original]
                    color = mesh['colors'][original]
                    if len(color) != 4:
                        raise ValueError('Scenery vertex color must have four components')
                    vertices.append([xyz[0], xyz[1], u*main['scale'][0]+main['offset'][0],
                                     1-(v*main['scale'][1]+main['offset'][1]),
                                     *(a*b for a, b in zip(color, tint))])
                    depths.append(xyz[2])
                indices.append(remap[original])
            if not indices:
                continue
            if len(vertices) >= 65536 or not all(math.isfinite(n) for v in vertices for n in v):
                raise ValueError('Invalid runtime scenery geometry')
            result.append(dict(texture=tex_index, vertices=vertices, indices=indices,
                               depth=sum(depths)/len(depths), path_id=layer['path_id']))
    result.sort(key=lambda item: -item['depth'])
    return result, skipped


def build():
    data = json.loads((ROOT/'content/scenery.json').read_text())
    textures = sorted(data['textures'])
    indices = {key: index for index, key in enumerate(textures)}
    generated = ['// Generated by tools/build_scenery_runtime.py.', 'pub const TEXTURES: &[&[u8]] = &[']
    for key in textures:
        generated.append(f'    include_bytes!("../../../{data["textures"][key]["image"]}"),')
    generated.extend(['];', 'pub const DATA: &[u8] = include_bytes!("../../../assets/scenery.bin");', ''])
    (ROOT/'crates/epic-client/src/scenery_generated.rs').write_text('\n'.join(generated), encoding='utf-8')
    output = bytearray(b'EPICSC01'+struct.pack('<I', len(data['scenes'])))
    summaries = []
    for scene in data['scenes']:
        if len(scene['cameras']) != 1:
            raise ValueError('Expected unique scenery camera')
        camera = scene['cameras'][0]
        matrix = camera['world_matrix']
        if (not camera['orthographic'] or camera['orthographic_size'] <= 0 or
            camera['viewport'] != [0., 0., 1., 1.] or
            any(abs(matrix[r*4+c]-(r == c)) > 1e-5 for r in range(3) for c in range(3))):
            raise ValueError('Unsupported scenery camera projection')
        draws, skipped = batches(scene, data, indices)
        name = scene['id'].encode('utf-8')
        output.extend(struct.pack('<H', len(name))+name)
        output.extend(struct.pack('<7fI', *camera['background'], matrix[3], matrix[7], camera['orthographic_size'], len(draws)))
        for draw in draws:
            output.extend(struct.pack('<HII', draw['texture'], len(draw['vertices']), len(draw['indices'])))
            for vertex in draw['vertices']:
                output.extend(struct.pack('<8f', *vertex))
            output.extend(struct.pack('<'+'H'*len(draw['indices']), *draw['indices']))
        summaries.append(dict(id=scene['id'], draws=len(draws), vertices=sum(len(d['vertices']) for d in draws), skipped=skipped))
    (ROOT/'assets/scenery.bin').write_bytes(output)
    report = dict(format='EPICSC01', source_sha256=hashlib.sha256((ROOT/'content/scenery.json').read_bytes()).hexdigest(),
                  sha256=hashlib.sha256(output).hexdigest(), bytes=len(output), textures=len(textures), scenes=summaries,
                  limitations=data['limitations']+['Depth sorted static triangles; original shader and runtime camera effects pending'])
    (ROOT/'content/scenery-runtime.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    print('Packed',len(summaries),'scenes;',sum(s['draws'] for s in summaries),'draws;',len(output),'bytes')


if __name__ == '__main__':
    build()
