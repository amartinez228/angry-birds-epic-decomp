"""Recover pause/sidebar, boss geometry, health and battle-HUD curves.

--bundle uses UnityPy 1.25.4 and Pillow. --check is source-only and verifies
the prepared PNG, generated Rust and saved manifest's finite/stepped curves.
Controller coroutine bodies are absent: fill sequencing is not claimed exact.
"""
import argparse
import json
import math
import struct
from pathlib import Path

from recover_reference_layouts import BUNDLE_SHA, REVISION, sha
from recover_reference_ui import atlas_sprites

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'content/ui-motion.json'
GENERATED = ROOT / 'crates/epic-client/src/ui_motion_generated.rs'
IMAGE = ROOT / 'assets/ui/motion_atlas.png'
WIDGETS = {
    'pause_button': ('level10', 683), 'pause_icon': ('level10', 525),
    'continue_body': ('level21', 139), 'continue_icon': ('level21', 155),
    'retry_body': ('level21', 156), 'retry_icon': ('level21', 176),
    'map_body': ('level21', 196), 'map_icon': ('level21', 149),
    'sidebar': ('level21', 194), 'sound_body': ('level21', 188), 'sound_on': ('level21', 141),
    'board_bottom': ('level21', 169), 'board_left': ('level21', 158),
    'board_right': ('level21', 191), 'board_top': ('level21', 173), 'board_header': ('level21', 152),
    'boss_body': ('sharedassets27.assets', 1235), 'boss_fill': ('sharedassets27.assets', 1147),
    'health_body': ('sharedassets27.assets', 1179), 'health_fill': ('sharedassets27.assets', 1198),
    'health_damage': ('sharedassets27.assets', 1157), 'health_indicator': ('sharedassets27.assets', 1204),
    **{'paper_' + key: ('level21', value) for key, value in {
        'tl':166, 't':175, 'tr':140, 'l':153, 'c':182, 'r':181, 'bl':154, 'b':170, 'br':190}.items()},
}


def number(value):
    if math.isnan(value):
        raise ValueError('NaN curve tangent')
    return str(value) if math.isfinite(value) else ('inf' if value > 0 else '-inf')


def literal(value):
    if value == 'inf':
        return 'f32::INFINITY'
    if value == '-inf':
        return 'f32::NEG_INFINITY'
    value = float(value)
    # Enough significant digits to round-trip f32, permitting original tangents.
    return f'{value:.9g}_f32'


def rust_source(m):
    lines = ['// Generated by tools/recover_ui_motion.py; do not edit.',
             'const IMAGE: &[u8] = include_bytes!("../../../assets/ui/motion_atlas.png");',
             '#[rustfmt::skip]', 'static ART: &[Art] = &[']
    for s in m['sprites']:
        widget = s['widget']
        lines.append('    Art { name: %s, rect: [%s], border: [%s], size: [%s], offset: [%s] },' % (
            json.dumps(s['key']), ', '.join(literal(v) for v in s['rect']),
            ', '.join(literal(v) for v in s['border']), ', '.join(literal(v) for v in widget['size']),
            ', '.join(literal(v) for v in widget['position'][:2])))
    lines += ['];', '#[allow(clippy::excessive_precision)]', '#[rustfmt::skip]', 'static CURVES: &[Curve] = &[']
    for clip in m['clips']:
        for c in clip['curves']:
            keys = ', '.join('[' + ', '.join(literal(v) for v in k) + ']' for k in c['keys'])
            lines.append('    Curve { clip: %s, path: %s, property: %s, keys: &[%s] },' % (
                json.dumps(clip['key']), json.dumps(c['path']), json.dumps(c['property']), keys))
    lines += ['];', '#[allow(clippy::excessive_precision)]', '#[rustfmt::skip]', 'static PLACEMENTS: &[Placement] = &[']
    for p in m['placements']:
        lines.append('    Placement { name: %s, rect: [%s], color: [%s], group: %s },' % (
            json.dumps(p['key']), ', '.join(literal(v) for v in p['rect']),
            ', '.join(literal(v) for v in p['color']), json.dumps(p['group'])))
    lines += ['];', '#[rustfmt::skip]', 'static BOSS_IDS: &[&str] = &[']
    lines += ['    ' + json.dumps(row['id']) + ',' for row in m['boss_selection']]
    return '\n'.join(lines + ['];', ''])


def recover(path):
    import UnityPy
    from PIL import Image
    data = Path(path).read_bytes()
    if sha(data) != BUNDLE_SHA:
        raise ValueError('Unexpected reference bundle')
    env = UnityPy.load(data)
    objects = {(o.assets_file.name, o.path_id): o for o in env.objects}
    def resolve(obj, file_id, path_id):
        filename = obj.assets_file.name if file_id == 0 else obj.assets_file.externals[file_id - 1].path.split('/')[-1]
        return objects[filename, path_id]
    def transform(obj):
        go = resolve(obj, *struct.unpack_from('<iq', obj.get_raw_data()))
        transforms = [p.component.deref() for p in go.read().m_Component if p.component.deref().type.name == 'Transform']
        result, = transforms
        return result
    atlas_cache = {}
    def atlas(obj):
        key = obj.assets_file.name, obj.path_id
        if key not in atlas_cache:
            material_id, rows = atlas_sprites(obj.get_raw_data())
            material = objects[obj.assets_file.name, material_id]
            texture_obj = dict(material.read().m_SavedProperties.m_TexEnvs)['_MainTex'].m_Texture.deref()
            atlas_cache[key] = (rows, texture_obj.read().image, dict(
                file=key[0], id=key[1], raw_sha256=sha(obj.get_raw_data()),
                texture_file=texture_obj.assets_file.name, texture_id=texture_obj.path_id,
                texture_raw_sha256=sha(texture_obj.get_raw_data())))
        return atlas_cache[key]
    selected = []
    placements = []
    for key, location in WIDGETS.items():
        obj = objects[location]
        raw = obj.get_raw_data()
        pivot, w, h, depth = struct.unpack_from('<4i', raw, 132)
        if key.startswith(('health_', 'boss_')) and pivot != 4:
            raise ValueError('Expected centered health widget')
        name_size, = struct.unpack_from('<I', raw, 264)
        name = raw[268:268 + name_size].decode()
        source_atlas = resolve(obj, *struct.unpack_from('<iq', raw, 252))
        rows, image, identity = atlas(source_atlas)
        row = rows[name]
        x, y, sw, sh = row['rect']
        if min(x, y) < 0 or min(sw, sh, w, h) <= 0 or x + sw > image.width or y + sh > image.height:
            raise ValueError('Invalid widget/art bounds')
        crop = image.crop((x, y, x + sw, y + sh))
        t_obj = transform(obj)
        t = t_obj.read()
        selected.append(dict(key=key, name=name, crop=crop, source_rect=row['rect'],
                             border=row['border'], source_rgba_sha256=sha(crop.tobytes()),
                             atlas=identity, widget=dict(file=location[0], id=location[1],
                             raw_sha256=sha(raw), size=[w, h], pivot=pivot, depth=depth,
                             position=[getattr(t.m_LocalPosition, a) for a in 'xyz'],
                             transform_id=t_obj.path_id, transform_raw_sha256=sha(t_obj.get_raw_data()))))
        if key.startswith(('health_', 'boss_')):
            continue
        # Accumulate saved hierarchy transforms to the authored 1280x720 canvas.
        position = [0., 0.]
        current = t_obj
        while current:
            node = current.read()
            if any(abs(getattr(node.m_LocalScale, a) - 1.) > 1e-6 for a in 'xy'):
                raise ValueError('Unexpected scaled pause hierarchy')
            position[0] += node.m_LocalPosition.x
            position[1] += node.m_LocalPosition.y
            current = node.m_Father.deref() if node.m_Father.path_id else None
        # The pause button's saved child is offscreen; its Enter clip settles it.
        if key in ['pause_button', 'pause_icon']:
            position[1] -= 250.
        px, py = 640. + position[0], 360. - position[1]
        rect = [px - w * (pivot % 3) / 2, py - h * (pivot // 3) / 2, w, h]
        group = ('button' if key.startswith('pause_') else 'board' if key.startswith(('board_', 'paper_'))
                 else 'sound' if key.startswith('sound_') else 'navigation')
        placements.append(dict(key=key, rect=rect, color=list(struct.unpack_from('<4f', raw, 116)), group=group))
    # Resolve the two alternatives not saved as active widget names.
    for key, name, template in [('sound_off', 'Sound_Off', 'sound_on'),
                                ('health_heal', 'Healthbar_Small_Bar_Heal', 'health_damage')]:
        original = next(s for s in selected if s['key'] == template)
        source_atlas = objects[original['atlas']['file'], original['atlas']['id']]
        rows, image, identity = atlas(source_atlas)
        x, y, w, h = rows[name]['rect']
        crop = image.crop((x, y, x + w, y + h))
        selected.append(dict(key=key, name=name, crop=crop, source_rect=[x,y,w,h],
                             border=rows[name]['border'], source_rgba_sha256=sha(crop.tobytes()),
                             atlas=identity, widget=original['widget'], alternative_to=template))
    packed = Image.new('RGBA', (1024, 1024))
    x, y, shelf = 2, 2, 0
    for s in sorted(selected, key=lambda s: (-s['crop'].height, -s['crop'].width, s['key'])):
        crop = s.pop('crop')
        w, h = crop.size
        if x + w + 2 > 1024:
            x, y, shelf = 2, y + shelf + 4, 0
        if y + h + 2 > 1024:
            raise ValueError('UI atlas overflow')
        # Two-pixel edge extrusion preserves clamp sampling under filtering.
        for dy in range(-2, h + 2):
            source_y = min(max(dy, 0), h - 1)
            line = crop.crop((0, source_y, w, source_y + 1))
            packed.paste(line, (x, y + dy))
            for dx in [-2, -1, w, w + 1]:
                packed.putpixel((x + dx, y + dy), crop.getpixel((min(max(dx, 0), w - 1), source_y)))
        s['rect'] = [x, y, w, h]
        x, shelf = x + w + 4, max(shelf, h)
    clips = []
    for file, tid, prefix in [('sharedassets27.assets', 825, 'small'),
                              ('sharedassets27.assets', 775, 'boss'), ('level21', 110, 'pause'),
                              ('level10',217,'progress'), ('level10',306,'rage'),
                              ('level10',351,'pause_button')]:
        go = objects[file, tid].read().m_GameObject.read()
        animation, = [p.component.deref() for p in go.m_Component if p.component.deref().type.name == 'Animation']
        for reference in animation.read().m_Animations:
            obj = reference.deref()
            tree = obj.read_typetree()
            curves = []
            for category, prop, axes in [('m_PositionCurves', 'position', 'xy'),
                                          ('m_ScaleCurves', 'scale', 'xy'), ('m_FloatCurves', '', '')]:
                for c in tree[category]:
                    if c['path'].startswith('Initiative'):
                        continue
                    if category == 'm_FloatCurves' and c['attribute'] not in ['mAlpha','mColor.a','mColor.r','mColor.g','mColor.b']:
                        continue
                    for axis in axes or ['']:
                        keys = []
                        for k in c['curve']['m_Curve']:
                            if k.get('weightedMode', 0):
                                raise ValueError('Weighted UI curve unsupported')
                            values = [k['time']] + [k[field][axis] if axis else k[field]
                                                       for field in ['value','inSlope','outSlope']]
                            keys.append([v if math.isfinite(v) else number(v) for v in values])
                        curves.append(dict(path=c['path'], property=prop+'.'+axis if axis else c['attribute'], keys=keys))
            clips.append(dict(key=prefix+'_'+tree['m_Name'].split('_')[-1].lower(), name=tree['m_Name'],
                              file=obj.assets_file.name, id=obj.path_id, raw_sha256=sha(obj.get_raw_data()), curves=curves))
    campaign = json.loads((ROOT / 'content/campaign.json').read_text())
    # This is an explicit presentation routing policy, not a recovered native
    # SpawnHealthBars branch: that body is absent from the supplied disassembly.
    boss_ids = [dict(id=p['id'], size_type=p['size_type']) for p in campaign['pigs'] if p['size_type'] == 3]
    spacer = objects['sharedassets27.assets',767]
    spacer_nodes = []
    for transform_obj in [spacer,*[p.deref() for p in spacer.read().m_Children]]:
        node=transform_obj.read();go=node.m_GameObject.read()
        spacer_nodes.append(dict(transform_id=transform_obj.path_id,name=go.m_Name,
                                 transform_sha256=sha(transform_obj.get_raw_data()),
                                 position=[getattr(node.m_LocalPosition,a) for a in 'xyz'],
                                 components=[dict(id=p.component.path_id,type=p.component.deref().type.name,
                                                  raw_sha256=sha(p.component.deref().get_raw_data()),
                                                  serialized_hex=p.component.deref().get_raw_data().hex())
                                             for p in go.m_Component]))
    controller=objects['sharedassets27.assets',1167].get_raw_data()
    packed.save(IMAGE)
    manifest = dict(reference='https://github.com/DarkTerraYT/EpicWeb', revision=REVISION,
                    bundle_sha256=BUNDLE_SHA, image_sha256=sha(IMAGE.read_bytes()), image_size=[1024,1024],
                    sprites=sorted(selected,key=lambda s:s['key']), placements=placements, clips=clips,
                    boss_selection=boss_ids,
                    unresolved_health_spacer=dict(file='sharedassets27.assets',nodes=spacer_nodes,
                        controller_id=1167,controller_hex=controller.hex(),controller_sha256=sha(controller),
                        interpretation='Prefab and controller bytes only; spacer count/spacing requires missing native method bodies'),
                    limitations=['Native health controller bodies/interrupt semantics and exact fill coroutine order are unavailable',
                                 'Largest campaign size_type=3 selects boss frame as an explicit provisional routing policy',
                                 'World-event segmented bars require event battle models and are separate from the campaign boss prefab',
                                 'Initiative text animation and remote news content are not reconstructed here'])
    OUTPUT.write_text(json.dumps(manifest,indent=2,allow_nan=False)+'\n')
    GENERATED.write_text(rust_source(manifest))
    print('Recovered',len(selected),'sprites and',len(clips),'pause/health/HUD clips')


def check():
    m = json.loads(OUTPUT.read_text())
    if m['revision'] != REVISION or m['bundle_sha256'] != BUNDLE_SHA:
        raise ValueError('Unexpected source identity')
    data = IMAGE.read_bytes()
    if (data[:8] != b'\x89PNG\r\n\x1a\n' or sha(data) != m['image_sha256']
            or list(struct.unpack_from('>II',data,16)) != m['image_size']):
        raise ValueError('Changed UI atlas')
    if {s['key'] for s in m['sprites']} != set(WIDGETS)|{'sound_off','health_heal'}:
        raise ValueError('Changed sprite selection')
    for sprite in m['sprites']:
        x,y,w,h=sprite['rect']
        if min(x,y)<2 or min(w,h)<=0 or x+w+2>1024 or y+h+2>1024:
            raise ValueError('Invalid packed sprite bounds')
    campaign=json.loads((ROOT/'content/campaign.json').read_text())
    if m['boss_selection'] != [dict(id=p['id'],size_type=p['size_type']) for p in campaign['pigs'] if p['size_type']==3]:
        raise ValueError('Stale campaign boss routing')
    if {c['key'] for c in m['clips']} != ({p+'_'+k for p in ['small','boss']
            for k in ['show','hide','damage','heal','initiativefocus']}|{'pause_enter','pause_leave',
                'progress_enter','progress_leave','progress_update','rage_enter','rage_leave',
                'pause_button_enter','pause_button_leave'}):
        raise ValueError('Changed clip selection')
    spacer=m['unresolved_health_spacer']
    if sha(bytes.fromhex(spacer['controller_hex'])) != spacer['controller_sha256']:
        raise ValueError('Changed spacer controller evidence')
    for node in spacer['nodes']:
        for component in node['components']:
            if sha(bytes.fromhex(component['serialized_hex'])) != component['raw_sha256']:
                raise ValueError('Changed spacer prefab evidence')
    for clip in m['clips']:
        for c in clip['curves']:
            times = [k[0] for k in c['keys']]
            if times != sorted(set(times)) or not times:
                raise ValueError('Invalid key sequence')
            for key in c['keys']:
                if len(key) != 4 or not all(math.isfinite(v) for v in key[:2]):
                    raise ValueError('Invalid curve values')
                if not all(v in ['inf','-inf'] if isinstance(v,str) else math.isfinite(v) for v in key[2:]):
                    raise ValueError('Invalid tangent')
    if GENERATED.read_text() != rust_source(m):
        raise ValueError('Stale generated motion code')
    print('Pause/boss/health art and curve generation match')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--bundle')
    mode.add_argument('--check',action='store_true')
    args = parser.parse_args()
    check() if args.check else recover(args.bundle)
