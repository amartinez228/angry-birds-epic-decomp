"""Pack recovered music bindings used by current native game screens.

All recovered compressed clips remain in content/audio.json; PCM embeddings
are limited to the tracks needed by the initial Windows music backend.
"""
import hashlib
import json

from recover_art import ROOT


def build():
    data = json.loads((ROOT/'content/audio.json').read_text())
    by_hash = {clip['sha256']:clip for clip in data['clips']}
    wanted = ['music_worldmap', 'music_camp', 'Music_Combat_Basic', 'Music_Combat_Special', 'music_battle_win', 'music_battle_lose']
    output = ['// Generated by tools/build_music_runtime.py.', 'pub const MUSIC: &[MusicDefinition] = &[']
    report = []
    for identifier in wanted:
        matches = [sound for sound in data['sounds'] if sound['id'] == identifier]
        if len(matches) != 1:
            raise ValueError('Ambiguous music ID')
        sound = matches[0]
        if not sound['primary_music'] or len(sound['clips']) != len(sound['asset_names']) or sound['muted']:
            raise ValueError('Incomplete music binding')
        # Native per-channel gain and crossfades need reconstruction. Selected
        # tracks all have unity per-sound gain; don't discard another gain.
        if sound['volume'] != 1.:
            raise ValueError('Music backend requires per-sound gain support')
        output.append(f'    MusicDefinition {{ id: {json.dumps(identifier)}, looping: {str(sound["looping"]).lower()}, tracks: &[')
        names = []
        for digest in sound['clips']:
            clip = by_hash[digest]
            if not clip['wav']:
                raise ValueError('Missing decoded music PCM')
            output.append('        MusicTrack { name: '+json.dumps(clip['name'])+', wave: include_bytes!("../../../'+clip['wav']+'") },')
            names.append(clip['name'])
        output.append('    ] },')
        report.append(dict(id=identifier, tracks=names, looping=sound['looping'], fade_time=sound['fade_time']))
    output.extend(['];', ''])
    (ROOT/'crates/epic-client/src/music_generated.rs').write_text('\n'.join(output), encoding='utf-8')
    (ROOT/'content/music-runtime.json').write_text(json.dumps(dict(
        source_sha256=hashlib.sha256((ROOT/'content/audio.json').read_bytes()).hexdigest(), sounds=report,
        limitations=['Windows WinMM primary music only; other platform backends, native mixer/channel gains, secondary music, crossfades and sound effects unfinished',
                     'Current Camp/Shop share camp music; original screen-state transitions still need comparison']), indent=2)+'\n', encoding='utf-8')
    print('Packed', len(report), 'music definitions;', sum(len(item['tracks']) for item in report), 'track bindings')


if __name__ == '__main__':
    build()
