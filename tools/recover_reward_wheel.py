"""Recover original wheel art and selected scene evidence from pinned EpicWeb.

--bundle needs UnityPy/Pillow; --check uses the Python standard library.
The Rust receipt screen adapts placement and timing; this is visual evidence,
not a reconstruction of the original reward controller or RNG.
"""
import argparse
import json
import struct
from pathlib import Path

from recover_reference_layouts import BUNDLE_SHA, REVISION, sha
from recover_reference_ui import atlas_sprites

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'content/reward-wheel.json'
GENERATED = ROOT / 'crates/epic-client/src/reward_wheel_generated.rs'
IMAGE = ROOT / 'assets/ui/reward_atlas.png'
SPRITES = {
    'static': 'WheelOfLoot_Static', 'spinning': 'WheelOfLoot_Spinning',
    'highlight': 'WheelOfLoot_Highlight', 'cog': 'WheelOfLoot_Cog',
    'active': 'WheelOfLoot_Marker_Active', 'inactive': 'WheelOfLoot_Marker_Inactive',
}
# Retain the half-wheel pivots/mirroring, slot rotations, fixed reward markers
# and highlight geometry, including the original one-pixel height differences.
TRANSFORMS = [381, 532, 534, 542, 378, 452, 314, 548, 401, 570, 374, 455, 348,
              423, 528, 515, 539, 436, 595, 586, 444, 408, 517, 538,
              565, 474, 477, 514, 573, 541, 310, 437, 439, 578, 438, 406, 375, 450]


def rust_source(manifest):
    lines = ['// Generated by tools/recover_reward_wheel.py; do not edit.',
             'const ATLAS: &[u8] = include_bytes!("../../../assets/ui/reward_atlas.png");',
             '#[rustfmt::skip]', 'static SPRITES: &[Sprite] = &[']
    for s in manifest['sprites']:
        lines.append('    Sprite { name: %s, rect: [%s] },' % (
            json.dumps(s['key']), ', '.join(str(v) + '.' for v in s['runtime_rect'])))
    return '\n'.join(lines + ['];', ''])


def recover(path):
    import UnityPy
    from PIL import Image
    bundle = Path(path).read_bytes()
    if sha(bundle) != BUNDLE_SHA:
        raise ValueError('Unexpected reference bundle')
    objects = {(o.assets_file.name, o.path_id): o for o in UnityPy.load(bundle).objects}
    atlas = objects['resources.assets', 43932]
    material_id, sprites = atlas_sprites(atlas.get_raw_data())
    if material_id != 19:
        raise ValueError('Unexpected material')
    material = objects['resources.assets', material_id].read()
    texture = dict(material.m_SavedProperties.m_TexEnvs)['_MainTex'].m_Texture.deref()
    source = texture.read().image
    packed = Image.new('RGBA', (1024, 512))
    outputs = []
    sx, sy, shelf = 2, 2, 0
    for key, name in sorted(SPRITES.items()):
        x, y, w, h = sprites[name]['rect']
        if min(x, y) < 0 or min(w, h) <= 0 or x + w > source.width or y + h > source.height:
            raise ValueError('Invalid crop')
        crop = source.crop((x, y, x + w, y + h))
        if sx + w + 2 > 1024:
            sx, sy, shelf = 2, sy + shelf + 4, 0
        if sy + h + 2 > 512:
            raise ValueError('Reward atlas overflow')
        # Edge extrusion, including corners, prevents linear filtering seams.
        padded = Image.new('RGBA', (w + 4, h + 4))
        padded.paste(crop, (2, 2))
        for d in (0, 1):
            padded.paste(crop.crop((0, 0, 1, h)), (d, 2))
            padded.paste(crop.crop((w - 1, 0, w, h)), (w + 2 + d, 2))
            padded.paste(crop.crop((0, 0, w, 1)), (2, d))
            padded.paste(crop.crop((0, h - 1, w, h)), (2, h + 2 + d))
        for cx, px in [(0, 0), (w - 1, w + 2)]:
            for cy, py in [(0, 0), (h - 1, h + 2)]:
                padded.paste(crop.getpixel((cx, cy)), (px, py, px + 2, py + 2))
        packed.paste(padded, (sx - 2, sy - 2))
        outputs.append(dict(key=key, name=name, source_rect=[x, y, w, h],
                            source_rgba_sha256=sha(crop.tobytes()), runtime_rect=[sx, sy, w, h]))
        sx, shelf = sx + w + 4, max(shelf, h)
    nodes = []
    for identifier in TRANSFORMS:
        obj = objects['level11', identifier]
        t = obj.read()
        go = t.m_GameObject.read()
        components = []
        for pair in go.m_Component:
            c = pair.component.deref()
            row = dict(id=c.path_id, type=c.type.name, raw_sha256=sha(c.get_raw_data()))
            if c.type.name == 'MonoBehaviour':
                row['serialized_hex'] = c.get_raw_data().hex()
            components.append(row)
        nodes.append(dict(id=identifier, name=go.m_Name, parent=t.m_Father.path_id,
                          position=[getattr(t.m_LocalPosition, a) for a in 'xyz'],
                          scale=[getattr(t.m_LocalScale, a) for a in 'xyz'],
                          rotation=[getattr(t.m_LocalRotation, a) for a in 'xyzw'],
                          raw_sha256=sha(obj.get_raw_data()), components=components))
    packed.save(IMAGE)
    manifest = dict(reference='https://github.com/DarkTerraYT/EpicWeb', revision=REVISION,
                    bundle_sha256=BUNDLE_SHA,
                    atlas=dict(file='resources.assets', id=43932, raw_sha256=sha(atlas.get_raw_data()),
                               texture_id=texture.path_id, texture_raw_sha256=sha(texture.get_raw_data())),
                    scene_file='level11', nodes=nodes,
                    nodes_sha256=sha(json.dumps(nodes, sort_keys=True).encode()), sprites=outputs,
                    image=dict(path=IMAGE.relative_to(ROOT).as_posix(), size=[1024, 512], sha256=sha(IMAGE.read_bytes())),
                    limitations=['Adapted receipt layout and 1.4-second spin, not native controller scheduling',
                                 'Ordinal slot labels replace original loot previews; inventory list shows actual delivered rewards',
                                 'Original marker artwork/spacing and wheel half assembly; marker activation order adapted to wrapped receipt selection',
                                 'Bonus wheels, rerolls, reward effects, sounds and original victory transition remain unfinished'])
    MANIFEST.write_text(json.dumps(manifest, indent=2) + '\n')
    GENERATED.write_text(rust_source(manifest))
    check()


def check():
    m = json.loads(MANIFEST.read_text())
    if m['revision'] != REVISION or m['bundle_sha256'] != BUNDLE_SHA:
        raise ValueError('Unexpected source')
    if {s['key']: s['name'] for s in m['sprites']} != SPRITES:
        raise ValueError('Changed sprite selection')
    if ([n['id'] for n in m['nodes']] != TRANSFORMS or
            sha(json.dumps(m['nodes'], sort_keys=True).encode()) != m['nodes_sha256']):
        raise ValueError('Changed scene evidence')
    for n in m['nodes']:
        for c in n['components']:
            if 'serialized_hex' in c and sha(bytes.fromhex(c['serialized_hex'])) != c['raw_sha256']:
                raise ValueError('Changed widget evidence')
    image = IMAGE.read_bytes()
    if (sha(image) != m['image']['sha256'] or image[:8] != b'\x89PNG\r\n\x1a\n' or
            list(struct.unpack_from('>II', image, 16)) != [1024, 512]):
        raise ValueError('Changed atlas')
    if GENERATED.read_text() != rust_source(m):
        raise ValueError('Stale generated Rust')
    print('Reward wheel: six sprites, 38 scene transforms, generated Rust and atlas match')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--bundle')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    check() if args.check else recover(args.bundle)
