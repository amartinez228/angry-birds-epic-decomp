"""Prepare the next reference-based battle HUD from the pinned UnityFS bundle.

--bundle requires UnityPy 1.25.4 and Pillow; --check uses only the standard
library and checks the generated Rust, source hierarchy links and packed PNG.
"""
import argparse
import json
import struct
from pathlib import Path

from recover_reference_layouts import BUNDLE_SHA, REVISION, sha, validate
from recover_reference_ui import atlas_sprites

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'content/battle-hud.json'
GENERATED = ROOT / 'crates/epic-client/src/battle_hud_generated.rs'
IMAGE = ROOT / 'assets/ui/battle_atlas.png'
SPRITES = {
    'rage_body': 'RageOMeter_Body', 'rage_fill': 'RageOMeter_Fill',
    'rage_stem': 'RageOMeter_Stipe', 'rage_ready': 'RageOMeter_Ready',
    'track_end': 'BattleProgress_Track_End', 'track_middle': 'BattleProgress_Track_Middle',
    'bird': 'BattleProgress_RedBird_Idle', 'bird_shadow': 'BattleProgress_RedBird_Shadow',
    'wheel': 'BattleProgress_WheelOfFortune',
    'health_body': 'Healthbar_Small_Body',
    'health_fill': 'Healthbar_Small_Bar_Health',
}
ANCHORS = {'progress': '2_BattleProgress', 'rage': '5_RageOMeter'}


def anchors():
    manifest = json.loads((ROOT / 'content/reference-layouts.json').read_text())
    validate(manifest)
    scene = next(s for s in manifest['scenes'] if s['file'] == 'level10')
    nodes = {n['name']: n for n in scene['nodes']}
    root = nodes['Menu_Battleground']
    calibrated = set()
    for node in scene['nodes']:
        if node['parent'] != root['transform_id']:
            continue
        for component in node['components']:
            if component.get('script') != 'LayoutControl':
                continue
            raw = bytes.fromhex(component['serialized_hex'])
            if len(raw) != 92:
                raise ValueError('Unexpected battle anchor layout')
            anchor, = struct.unpack_from('<i', raw, 60)
            ox, oy, oz = struct.unpack_from('<3f', raw, 76)
            if not 0 <= anchor <= 8 or node['position'] != [
                    (anchor % 3 - 1) * 640 + ox, (1 - anchor // 3) * 360 + oy, oz]:
                raise ValueError('Battle anchor model conflicts with saved coordinates')
            calibrated.add(anchor)
    if not {0, 1, 2, 7, 8}.issubset(calibrated):
        raise ValueError('Missing independent corner/edge calibration evidence')
    result = []
    for key, name in ANCHORS.items():
        node = nodes[name]
        c, = [c for c in node['components'] if c.get('script') == 'LayoutControl']
        raw = bytes.fromhex(c['serialized_hex'])
        if (len(raw) != 92 or struct.unpack_from('<iq', raw, 32) != (0, root['game_object_id'])
                or raw[44:60] != bytes(16) or raw[64:76] != bytes(12) or raw[88:] != bytes(4)):
            raise ValueError('Unsupported root LayoutControl variant')
        anchor, = struct.unpack_from('<i', raw, 60)
        offset = list(struct.unpack_from('<3f', raw, 76))
        if not 0 <= anchor <= 8:
            raise ValueError('Invalid anchor index')
        # Inferred nine-point enum ordering. Every selected anchor independently
        # reproduces its saved position on the 1280x720 authored canvas.
        saved = [(anchor % 3 - 1) * 640 + offset[0],
                 (1 - anchor // 3) * 360 + offset[1], offset[2]]
        if saved != node['position']:
            raise ValueError('Anchor inference does not reproduce the authored position')
        result.append(dict(key=key, name=name, anchor=anchor, offset=offset,
                           transform_id=node['transform_id'], component_id=c['id'],
                           raw_sha256=c['raw_sha256']))
    return result


def rust_source(manifest):
    lines = ['// Generated by tools/recover_battle_hud.py; do not edit.',
             'const ATLAS: &[u8] = include_bytes!("../../../assets/ui/battle_atlas.png");']
    for row in manifest['anchors']:
        lines.append('#[rustfmt::skip]')
        lines.append('const %s: Anchor = Anchor { column: %d, row: %d, offset: [%s] };' % (
            row['key'].upper(), row['anchor'] % 3, row['anchor'] // 3,
            ', '.join(str(v) for v in row['offset'][:2])))
    lines += ['#[rustfmt::skip]', 'static SPRITES: &[Sprite] = &[']
    for sprite in manifest['sprites']:
        lines.append('    Sprite { name: %s, rect: [%s] },' % (
            json.dumps(sprite['key']), ', '.join(str(v) + '.' for v in sprite['runtime_rect'])))
    return '\n'.join(lines + ['];', ''])


def recover(path):
    import UnityPy
    from PIL import Image
    bundle = Path(path).read_bytes()
    if sha(bundle) != BUNDLE_SHA:
        raise ValueError('Unexpected reference bundle')
    env = UnityPy.load(bundle)
    objects = {(o.assets_file.name, o.path_id): o for o in env.objects}
    atlas = objects['resources.assets', 43932]
    raw = atlas.get_raw_data()
    material, sprites = atlas_sprites(raw)
    if material != 19 or atlas.assets_file.objects[struct.unpack_from('<q', raw, 4)[0]].read().m_Name != 'BattleElements':
        raise ValueError('Unexpected battle atlas identity')
    material_obj = objects['resources.assets', material]
    ref = dict(material_obj.read().m_SavedProperties.m_TexEnvs)['_MainTex'].m_Texture
    if ref.m_FileID:
        raise ValueError('Unexpected external texture')
    texture_obj = objects['resources.assets', ref.m_PathID]
    texture = texture_obj.read()
    if texture.m_Name != 'BattleElements':
        raise ValueError('Unexpected battle texture')
    source = texture.image
    packed = Image.new('RGBA', (512, 512))
    outputs = []
    sx, sy, shelf = 2, 2, 0
    for key, name in sorted(SPRITES.items()):
        row = sprites[name]
        x, y, w, h = row['rect']
        if min(x, y) < 0 or min(w, h) <= 0 or x + w > source.width or y + h > source.height:
            raise ValueError('Invalid crop')
        crop = source.crop((x, y, x + w, y + h))
        if sx + w + 2 > 512:
            sx, sy, shelf = 2, sy + shelf + 4, 0
        if sy + h + 2 > 512:
            raise ValueError('Battle atlas overflow')
        packed.paste(crop, (sx, sy))
        for delta in (1, 2):
            packed.paste(crop.crop((0, 0, 1, h)), (sx - delta, sy))
            packed.paste(crop.crop((w - 1, 0, w, h)), (sx + w - 1 + delta, sy))
            packed.paste(crop.crop((0, 0, w, 1)), (sx, sy - delta))
            packed.paste(crop.crop((0, h - 1, w, h)), (sx, sy + h - 1 + delta))
        for cx, px in [(0, sx - 2), (w - 1, sx + w)]:
            for cy, py in [(0, sy - 2), (h - 1, sy + h)]:
                packed.paste(crop.getpixel((cx, cy)), (px, py, px + 2, py + 2))
        outputs.append(dict(key=key, name=name, source_rect=row['rect'],
                            source_rgba_sha256=sha(crop.tobytes()), runtime_rect=[sx, sy, w, h]))
        sx, shelf = sx + w + 4, max(shelf, h)
    # Enter clips override the offscreen saved child positions. Retain their
    # authored curves so the settled zero offset is supported by animation data.
    clips = []
    for animation_id, expected in [(446, 'BattleProgress_Enter'), (462, 'RageOMeter_Enter')]:
        animation = objects['level10', animation_id].read()
        matches = [p.deref() for p in animation.m_Animations if p.deref().read().m_Name == expected]
        clip, = matches
        tree = clip.read_typetree()
        curve, = [c for c in tree['m_PositionCurves'] if c['path'] == 'Animation']
        keys = [dict(time=k['time'], value=[k['value'][axis] for axis in 'xyz'])
                for k in curve['curve']['m_Curve']]
        if keys[-1]['value'] != [0., 0., 0.]:
            raise ValueError('Unexpected settled animation offset')
        clips.append(dict(file=clip.assets_file.name, id=clip.path_id, name=expected,
                          raw_sha256=sha(clip.get_raw_data()), path='Animation', keys=keys))
    # Original centered pepper geometry, including the authored 0.9 local scale.
    widgets = []
    for identifier, name in [(611, 'rage_body'), (589, 'rage_fill'), (572, 'rage_stem')]:
        obj = objects['level10', identifier]
        raw = obj.get_raw_data()
        width, height = struct.unpack_from('<2i', raw, 136)
        pivot, = struct.unpack_from('<i', raw, 132)
        if pivot != 4 or (width, height) != tuple(next(s['source_rect'][2:] for s in outputs if s['key'] == name)):
            raise ValueError('Unexpected centered rage widget geometry')
        widgets.append(dict(key=name, id=identifier, width=width, height=height,
                            pivot=pivot, raw_sha256=sha(raw)))
    health_widgets = []
    for identifier, key in [(1179, 'health_body'), (1198, 'health_fill')]:
        obj = objects['sharedassets27.assets', identifier]
        raw = obj.get_raw_data()
        pivot, width, height, depth = struct.unpack_from('<4i', raw, 132)
        atlas_file, atlas_id = struct.unpack_from('<iq', raw, 252)
        length, = struct.unpack_from('<I', raw, 264)
        sprite_name = raw[268:268 + length].decode('utf-8')
        if (atlas_file <= 0 or atlas_id != 43932 or sprite_name != SPRITES[key]
                or not obj.assets_file.externals[atlas_file - 1].path.endswith('resources.assets')):
            raise ValueError('Health widget does not bind to the selected original atlas/sprite')
        go = objects['sharedassets27.assets', struct.unpack_from('<q', raw, 4)[0]].read()
        transform, = [p.component.deref() for p in go.m_Component
                      if p.component.deref().type.name == 'Transform']
        t = transform.read()
        if (pivot != 4 or t.m_Father.path_id != 529
                or (width, height) != tuple(next(s['source_rect'][2:] for s in outputs if s['key'] == key))):
            raise ValueError('Unexpected standard health widget geometry')
        health_widgets.append(dict(key=key, file=obj.assets_file.name, id=identifier,
                                   size=[width, height], pivot=pivot, depth=depth,
                                   sprite_name=sprite_name, atlas_file='resources.assets', atlas_id=atlas_id,
                                   position=[getattr(t.m_LocalPosition, a) for a in 'xyz'],
                                   raw_sha256=sha(raw), transform_id=transform.path_id,
                                   transform_sha256=sha(transform.get_raw_data())))
    packed.save(IMAGE)
    manifest = dict(reference='https://github.com/DarkTerraYT/EpicWeb', revision=REVISION,
                    bundle_sha256=BUNDLE_SHA, anchors=anchors(),
                    anchor_interpretation='Inferred 3x3 row-major top-left through bottom-right; selected rows reproduce 1280x720 saved positions',
                    atlas=dict(file='resources.assets', id=43932, raw_sha256=sha(atlas.get_raw_data()),
                               material_id=material, texture_id=texture_obj.path_id,
                               texture_raw_sha256=sha(texture_obj.get_raw_data())),
                    image=dict(path=IMAGE.relative_to(ROOT).as_posix(), sha256=sha(IMAGE.read_bytes()), size=[512, 512]),
                    sprites=outputs, enter_clips=clips, rage_widgets=widgets,
                    health_widgets=health_widgets,
                    health_prefab=dict(file='sharedassets27.assets', game_object_id=317,
                                       transform_id=825, controller_id=1167,
                                       controller_raw_sha256=sha(objects['sharedassets27.assets', 1167].get_raw_data())),
                    limitations=['Settled HUD placement only; enter/leave animations are not played',
                                 'Wave-track width and wave icon motion are adapted to current battles',
                                 'Rage glow timing, particles, gold variant and drag gestures remain unfinished',
                                 'Health bars use the current actor placement; original following/visibility, change trails, spacers and boss segments remain unfinished'])
    MANIFEST.write_text(json.dumps(manifest, indent=2) + '\n')
    GENERATED.write_text(rust_source(manifest))
    print('Recovered', len(outputs), 'battle HUD sprites, two anchors and standard health widget geometry')


def check():
    manifest = json.loads(MANIFEST.read_text())
    if manifest['revision'] != REVISION or manifest['bundle_sha256'] != BUNDLE_SHA:
        raise ValueError('Unexpected reference build')
    if manifest['anchors'] != anchors() or GENERATED.read_text() != rust_source(manifest):
        raise ValueError('Stale battle HUD generation')
    if {s['key']: s['name'] for s in manifest['sprites']} != SPRITES:
        raise ValueError('Unexpected sprite selection')
    image = IMAGE.read_bytes()
    if (sha(image) != manifest['image']['sha256'] or image[:8] != b'\x89PNG\r\n\x1a\n'
            or list(struct.unpack_from('>II', image, 16)) != [512, 512]):
        raise ValueError('Changed battle atlas')
    print('Battle HUD anchors, generated Rust and packed PNG match')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--bundle')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    check() if args.check else recover(args.bundle)
