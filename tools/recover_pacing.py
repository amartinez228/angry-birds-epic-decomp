"""Recover the shipped PacingBalancing component, not constructor defaults.

This build serializes forty float fields in metadata declaration order. Match
the actual MonoScript reference before accepting a component, consume its exact
payload, and retain both component and source hashes for reproducible evidence.
"""
import hashlib
import json
import math
import re
import struct

from extract_unity import Reader
from recover_art import Extractor, ROOT
from recover_characters import Scene


def field_names():
    metadata = (ROOT / 'analysis/global-metadata.dat').read_bytes()
    if struct.unpack_from('<II', metadata) != (0xFAB11BAF, 23):
        raise ValueError('Expected IL2CPP metadata v23')
    strings, string_size = struct.unpack_from('<II', metadata, 24)
    types, type_size = struct.unpack_from('<II', metadata, 160)
    fields, field_size = struct.unpack_from('<II', metadata, 96)

    def name(index):
        if not 0 <= index < string_size:
            raise ValueError('String index outside metadata')
        end = metadata.index(b'\0', strings + index, strings + string_size)
        return metadata[strings + index:end].decode('utf-8')

    matches = []
    for at in range(types, types + type_size, 104):
        if name(struct.unpack_from('<I', metadata, at)[0]) != 'PacingBalancing':
            continue
        start = struct.unpack_from('<i', metadata, at + 48)[0]
        count = struct.unpack_from('<H', metadata, at + 84)[0]
        if count != 40 or not 0 <= start <= start + count <= field_size // 16:
            raise ValueError('Unsupported PacingBalancing declaration')
        rows = [struct.unpack_from('<II', metadata, fields + index * 16)
                for index in range(start, start + count)]
        if len({kind for _, kind in rows}) != 1:
            raise ValueError('Pacing field types differ')
        matches.append([name(index) for index, _ in rows])
    if len(matches) != 1:
        raise ValueError('Expected one PacingBalancing declaration')
    return matches[0], hashlib.sha256(metadata).hexdigest()


def decode_component(data, names):
    reader = Reader(data, 28)
    component_name = reader.string()
    values = reader.unpack('<' + 'f' * len(names))
    if reader.pos != len(data) or any(not math.isfinite(v) or v < 0 for v in values):
        raise ValueError('Invalid pacing payload or unconsumed component bytes')
    return component_name, dict(zip(names, values))


def recover():
    names, metadata_hash = field_names()
    extractor = Extractor()
    scene = Scene(extractor)
    scripts = [entry for entry in extractor.inventory
               if entry['class_id'] == 115 and entry.get('name') == 'PacingBalancing']
    if len(scripts) != 1:
        raise ValueError('Expected one PacingBalancing script')
    script = scripts[0]
    matches = []
    for entry in extractor.inventory:
        if entry['class_id'] != 114 or entry['size'] < 32:
            continue
        data = extractor.data(entry)
        pointer = struct.unpack_from('<iq', data, 16)
        if pointer[1] != script['path_id']:
            continue
        source = entry['source'].split('/')[-1]
        target = scene.resolve(source, pointer, 115)
        if target[0] != script['source'].split('/')[-1] or target[1] != script['path_id']:
            continue
        if Reader(target[2]).string() != 'PacingBalancing':
            raise ValueError('Pacing script reference mismatch')
        component_name, values = decode_component(data, names)
        matches.append(dict(source=entry, component_name=component_name,
                            component_sha256=hashlib.sha256(data).hexdigest(),
                            serialized_file_sha256=scene.file(source)[2], values=values))
    if len(matches) != 1:
        raise ValueError('Expected one shipped pacing component')
    result = dict(metadata_sha256=metadata_hash, script=script, **matches[0],
                  limitations=['Values are shipped scene settings. Native use sites must be traced separately; constructor defaults are not substituted.'])
    (ROOT / 'content/pacing.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    lines = ['// Generated by tools/recover_pacing.py from the original scene component.',
             '#[allow(dead_code)]', 'pub mod original_pacing {']
    for name, value in result['values'].items():
        constant = re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '_', name.removeprefix('m_')).upper()
        literal = next(format(value, f'.{precision}g') for precision in range(1, 10)
                       if struct.pack('<f', float(format(value, f'.{precision}g'))) == struct.pack('<f', value))
        if '.' not in literal and 'e' not in literal:
            literal += '.0'
        lines.append(f'    pub const {constant}: f32 = {literal};')
    lines.append('}')
    (ROOT / 'crates/epic-client/src/pacing_generated.rs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Recovered {len(names)} shipped pacing settings from {result["source"]["source"]}:{result["source"]["path_id"]}')


if __name__ == '__main__':
    recover()
