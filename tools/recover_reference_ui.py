"""Recover selected original NGUI artwork from the user's EpicWeb reference.

Preparation: UnityPy==1.25.4 (not a Rust runtime dependency).
Use --data PATH for the pinned EpicWeb.data download, or --check to verify the
committed manifest, PNGs and generated Rust using only the standard library.
The input is parsed as data; the WebAssembly game is never executed.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
REVISION = 'd6ff01fcd9497a95abc40be955957a3447b55227'
SOURCE_SHA = '0606bf5e355b335bee30bb4001b8a978720729122ac280af380c24183ad6506f'
MANIFEST = ROOT / 'content/reference-ui.json'
GENERATED = ROOT / 'crates/epic-client/src/ui_skin_generated.rs'
SELECTION = {
    'button': 'Button_Rectangle_Medium',
    'button_disabled': 'Button_Rectangle_Medium_D',
    'coin': 'Resource_Coin',
    'xp': 'Resource_XP',
    'star': 'BattleStars_Small',
    'lock': 'Lock',
    'xp_body': 'XPBar_Body',
    'xp_fill': 'XPBar_Fill',
    **{'paper_' + suffix.lower(): 'PaperLabel_' + suffix
       for suffix in ['TL', 'T', 'TR', 'L', 'C', 'R', 'BL', 'B', 'BR']},
}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def web_member(data, wanted):
    magic = b'UnityWebData1.0\0'
    if not data.startswith(magic):
        raise ValueError('Expected UnityWebData1.0')
    position = len(magic)
    end, = struct.unpack_from('<I', data, position)
    position += 4
    if not position <= end <= len(data):
        raise ValueError('Invalid web-data header')
    result = None
    while position < end:
        if position + 12 > end:
            raise ValueError('Truncated web-data entry')
        start, size, length = struct.unpack_from('<III', data, position)
        position += 12
        if position + length > end or start < end or start + size > len(data):
            raise ValueError('Invalid web-data entry bounds')
        name = data[position:position + length].decode('utf-8')
        position += length
        if name == wanted:
            if result is not None:
                raise ValueError('Duplicate web-data member')
            result = data[start:start + size]
    if result is None:
        raise ValueError('Missing web-data member')
    return result


def atlas_sprites(raw):
    """Read the pinned UIAtlas/UISpriteData field sequence, validating its tail.

    Rows are name, x/y/width/height, four border and four padding integers.
    The tail is pixel size 1, null replacement and empty legacy fields.
    """
    if len(raw) < 48:
        raise ValueError('Truncated atlas')
    length, = struct.unpack_from('<I', raw, 28)
    position = (32 + length + 3) & ~3
    material_file, material_id, count = struct.unpack_from('<iqi', raw, position)
    position += 16
    if material_file != 0 or not 0 < count < 1000:
        raise ValueError('Expected self-contained atlas material')
    sprites = {}
    for _ in range(count):
        length, = struct.unpack_from('<I', raw, position)
        position += 4
        if not 0 < length < 512:
            raise ValueError('Invalid sprite name length')
        name = raw[position:position + length].decode('utf-8')
        position = (position + length + 3) & ~3
        values = struct.unpack_from('<12i', raw, position)
        position += 48
        # Some unused glow sprites have negative authored borders. Retain raw
        # values here; require valid borders on every sprite selected below.
        if name in sprites or any(value < 0 for value in values[:4]):
            raise ValueError('Invalid/duplicate sprite')
        sprites[name] = dict(rect=list(values[:4]), border=list(values[4:8]),
                             padding=list(values[8:]))
    if raw[position:] != struct.pack('<f', 1.) + bytes(20):
        raise ValueError('Unsupported atlas tail/replacement')
    return material_id, sprites


def rust_source(manifest):
    lines = ['// Generated by tools/recover_reference_ui.py; do not edit.',
             '// Original game artwork via the user-selected EpicWeb reference.',
             'const ATLAS_IMAGE: &[u8] = include_bytes!("../../../assets/ui/atlas.png");',
             '#[rustfmt::skip]', 'static ASSETS: &[SpriteAsset] = &[']
    for row in manifest['sprites']:
        lines.append('    SpriteAsset { name: %s, origin: [%s], size: [%s], border: [%s] },' % (
            json.dumps(row['key']), ', '.join(str(v) + '.' for v in row['runtime_rect'][:2]),
            ', '.join(str(v) + '.' for v in row['rect'][2:]),
            ', '.join(str(v) + '.' for v in row['border'])))
    return '\n'.join(lines + ['];', ''])


def recover(path):
    import UnityPy
    import importlib.metadata
    from PIL import Image
    source = Path(path).read_bytes()
    if digest(source) != SOURCE_SHA:
        raise ValueError('Reference digest differs: review a new build before using it')
    bundle = web_member(source, 'data.unity3d')
    env = UnityPy.load(bundle)
    matches = []
    for obj in env.objects:
        if obj.type.name != 'MonoBehaviour' or obj.assets_file.name != 'sharedassets0.assets':
            continue
        raw = obj.get_raw_data()
        if len(raw) < 48 or struct.unpack_from('<iq', raw, 16) != (1, 49):
            continue
        game_object = struct.unpack_from('<q', raw, 4)[0]
        if obj.assets_file.objects[game_object].read().m_Name != 'GenericElements':
            continue
        material_id, sprites = atlas_sprites(raw)
        material_obj = obj.assets_file.objects[material_id]
        texture_ref = dict(material_obj.read().m_SavedProperties.m_TexEnvs)['_MainTex'].m_Texture
        if texture_ref.m_FileID != 0:
            raise ValueError('Unexpected external UI texture')
        texture_obj = obj.assets_file.objects[texture_ref.m_PathID]
        texture = texture_obj.read()
        if texture.m_Name != 'GenericElements':
            raise ValueError('Atlas/texture identity mismatch')
        matches.append((obj, raw, material_obj, texture_obj, texture, sprites))
    if len(matches) != 1:
        raise ValueError('Expected exactly one pinned self-contained GenericElements atlas')
    obj, raw, material_obj, texture_obj, texture, sprites = matches[0]
    image = texture.image
    outputs = []
    packed = Image.new('RGBA', (512, 512))
    shelf_x, shelf_y, shelf_height = 2, 2, 0
    directory = ROOT / 'assets/ui'
    directory.mkdir(exist_ok=True)
    for key, name in sorted(SELECTION.items()):
        row = sprites[name]
        x, y, w, h = row['rect']
        if w <= 0 or h <= 0 or x + w > image.width or y + h > image.height:
            raise ValueError('Sprite outside texture bounds')
        left, right, top, bottom = row['border']
        if min(row['border']) < 0 or left + right > w or top + bottom > h:
            raise ValueError('Invalid sprite border')
        target = directory / (key + '.png')
        # NGUI atlas coordinates are top-left; UnityPy's decoded image uses
        # the same origin. Preserve pixels, alpha and authored border values.
        crop = image.crop((x, y, x + w, y + h))
        crop.save(target)
        if shelf_x + w + 2 > packed.width:
            shelf_x = 2
            shelf_y += shelf_height + 4
            shelf_height = 0
        if shelf_y + h + 2 > packed.height:
            raise ValueError('Selected UI sprites exceed runtime atlas')
        packed.paste(crop, (shelf_x, shelf_y))
        # Match per-sprite clamp-to-edge sampling in the shared atlas. These
        # padding pixels duplicate the edge; selected source pixels stay intact.
        for offset in (1, 2):
            packed.paste(crop.crop((0, 0, 1, h)), (shelf_x - offset, shelf_y))
            packed.paste(crop.crop((w - 1, 0, w, h)), (shelf_x + w - 1 + offset, shelf_y))
            packed.paste(crop.crop((0, 0, w, 1)), (shelf_x, shelf_y - offset))
            packed.paste(crop.crop((0, h - 1, w, h)), (shelf_x, shelf_y + h - 1 + offset))
        for cx, px in [(0, shelf_x - 2), (w - 1, shelf_x + w)]:
            for cy, py in [(0, shelf_y - 2), (h - 1, shelf_y + h)]:
                packed.paste(crop.getpixel((cx, cy)), (px, py, px + 2, py + 2))
        outputs.append(dict(key=key, name=name, **row,
                            runtime_rect=[shelf_x, shelf_y, w, h],
                            output=target.relative_to(ROOT).as_posix(),
                            png_sha256=digest(target.read_bytes())))
        shelf_x += w + 4
        shelf_height = max(shelf_height, h)
    packed.save(directory / 'atlas.png')
    manifest = dict(
        reference='https://github.com/DarkTerraYT/EpicWeb', revision=REVISION,
        data_url=f'https://media.githubusercontent.com/media/DarkTerraYT/EpicWeb/{REVISION}/Build/EpicWeb.data',
        data_sha256=SOURCE_SHA, bundle_sha256=digest(bundle),
        reference_product_version='3.0.1', unity_version='6000.3.4f1',
        decoder='UnityPy ' + importlib.metadata.version('UnityPy'),
        runtime_atlas=dict(output='assets/ui/atlas.png', size=list(packed.size),
                           sha256=digest((directory / 'atlas.png').read_bytes()),
                           padding=2, packing='unscaled RGBA copies with 2px edge extrusion; no source resampling'),
        atlas=dict(file=obj.assets_file.name, path_id=obj.path_id,
                   raw_sha256=digest(raw), material_path_id=material_obj.path_id,
                   texture_path_id=texture_obj.path_id, texture_size=list(image.size),
                   coordinate_origin='top_left', border_order=['left', 'right', 'top', 'bottom'],
                   texture_object_sha256=digest(texture_obj.get_raw_data())),
        sprites=outputs,
        limitations=['Visual reference supplied by the user; separate from the original APK evidence',
                     'UI artwork recovery, not a full scene/layout or behavior reconstruction',
                     'Original game artwork retains its original rights; no repository-wide license inferred'])
    MANIFEST.write_text(json.dumps(manifest, indent=2) + '\n')
    GENERATED.write_text(rust_source(manifest))
    print('Recovered', len(outputs), 'original UI sprites')


def check():
    manifest = json.loads(MANIFEST.read_text())
    if manifest['data_sha256'] != SOURCE_SHA or manifest['revision'] != REVISION:
        raise ValueError('Unexpected reference build')
    if [row['key'] for row in manifest['sprites']] != sorted(SELECTION):
        raise ValueError('UI selection differs from the reviewed set')
    if GENERATED.read_text() != rust_source(manifest):
        raise ValueError('Stale generated UI assets')
    for row in manifest['sprites']:
        png = (ROOT / row['output']).read_bytes()
        if digest(png) != row['png_sha256'] or png[:8] != b'\x89PNG\r\n\x1a\n':
            raise ValueError('Changed or invalid UI image')
        if list(struct.unpack_from('>II', png, 16)) != row['rect'][2:]:
            raise ValueError('UI image dimensions do not match the atlas')
    atlas = (ROOT / manifest['runtime_atlas']['output']).read_bytes()
    if digest(atlas) != manifest['runtime_atlas']['sha256']:
        raise ValueError('Changed runtime UI atlas')
    print('UI provenance, PNG hashes/dimensions and generated Rust match')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--data')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    check() if args.check else recover(args.data)
