"""Pack verified original projectile curves and static sprite quad geometry.

Instantiation resets the prefab root rotation to identity. Strip that authored
root pose, retain child transforms, and remove the tween object's rest position
because its world position is driven by CHMotionTween. No replacement art.
"""
import hashlib
import json
import math
import struct

from recover_art import Extractor, ROOT
from recover_characters import Scene, compose, pose_matrix, transform_point, count
from recover_projectiles import game_object
from extract_unity import Reader


def number(value):
    value = struct.unpack('<f', struct.pack('<f', value))[0]
    if not math.isfinite(value):
        raise ValueError('Nonfinite runtime projectile value')
    literal = next(format(value, f'.{precision}g') for precision in range(1, 10)
                   if struct.pack('<f', float(format(value, f'.{precision}g'))) == struct.pack('<f', value))
    return literal if '.' in literal or 'e' in literal else literal + '.0'


def inverse_rigid(matrix):
    rotation = [[matrix[row*4+column] for column in range(3)] for row in range(3)]
    for a in range(3):
        for b in range(3):
            if abs(sum(rotation[k][a]*rotation[k][b] for k in range(3)) - (a == b)) > 1e-4:
                raise ValueError('Projectile root is not a rigid transform')
    result = [0.] * 16
    for row in range(3):
        for column in range(3):
            result[row*4+column] = rotation[column][row]
        result[row*4+3] = -sum(result[row*4+k]*matrix[k*4+3] for k in range(3))
    result[15] = 1.
    return result


def object_transform(scene, source, object_id):
    target, _, _, components = game_object(scene, source, (0, object_id))
    transforms = []
    for pointer in components:
        resolved = scene.resolve(target, pointer)
        if scene.file(resolved[0])[0][resolved[1]][0] == 4:
            transforms.append((resolved[0], resolved[1]))
    if len(transforms) != 1:
        raise ValueError('Expected one projectile object transform')
    return transforms[0]


def build():
    path = ROOT / 'content/projectiles.json'
    original = json.loads(path.read_text(encoding='utf-8'))
    motions = json.loads((ROOT / 'content/motion.json').read_text(encoding='utf-8'))['components']
    by_id = {(item['source']['source'], item['source']['path_id']): item for item in motions}
    scene = Scene(Extractor())
    lines = ['// Generated by tools/build_projectile_runtime.py; original static sprites and curves.',
             f'pub static PROJECTILES: [ProjectileDefinition; {len(original["projectiles"])}] = [']
    geometries = []
    q = json.dumps
    vector = lambda values: '[' + ', '.join(number(value) for value in values) + ']'

    def keys(values):
        if any(a['time'] > b['time'] for a, b in zip(values, values[1:])):
            raise ValueError('Unordered projectile curve requires explicit recovery')
        return '&[' + ', '.join('MotionKey { time: '+number(key['time'])+', value: '+number(key['value'])+', incoming: '+number(key['incoming'])+', outgoing: '+number(key['outgoing'])+' }' for key in values) + ']'

    for item in original['projectiles']:
        for obj in item['hierarchy']:
            raw = scene.file(obj['source'])[0][obj['path_id']][1]
            reader = Reader(raw)
            reader.read(count(reader)*12+4)
            reader.string()
            reader.read(2)
            if reader.read(1) != b'\x01':
                raise ValueError('Inactive projectile hierarchy requires runtime visibility support')
        reference = item['motion_components'][0]['source']
        motion = by_id[reference['source'], reference['path_id']]
        if motion['timing'] != 0 or motion['duration'] <= 0 or motion['looping']:
            raise ValueError('Unsupported projectile motion clock')
        root = object_transform(scene, item['source'], item['root_path_id'])
        root_inverse = inverse_rigid(pose_matrix(scene, root[0], (0, root[1])))
        source = reference['source'].split('/')[-1]
        raw = scene.file(source)[0][reference['path_id']][1]
        owner = scene.resolve(source, struct.unpack_from('<iq', raw), 1)
        moving = object_transform(scene, owner[0], owner[1])
        moving_pose = compose(root_inverse, pose_matrix(scene, moving[0], (0, moving[1])))
        lines.extend(['    ProjectileDefinition {', f'        id: {q(item["id"])}, duration: {number(motion["duration"])},',
                      f'        start_offset: {vector(motion["start_offset"][:2])}, end_offset: {vector(motion["end_offset"][:2])},',
                      f'        curve: {keys(motion["curve"]["keys"])},', '        axes: &['])
        for axis in motion['axes']:
            lines.append(f'            ({axis["axis"]}, {keys(axis["curve"]["keys"])}),')
        lines.extend(['        ],', '        sprites: &['])
        for sprite in item['sprites']:
            if sprite['status'] != 'extracted':
                continue
            raw = scene.file(sprite['source'])[0][sprite['path_id']][1]
            obj = scene.resolve(sprite['source'], struct.unpack_from('<iq', raw), 1)
            transform = object_transform(scene, obj[0], obj[1])
            matrix = compose(root_inverse, pose_matrix(scene, transform[0], (0, transform[1])))
            # Native QuadMeshCreator: X Left/Center/Right; Y Top/Center/Bottom.
            width, height = sprite['size']
            xa, ya = sprite['alignment']
            if xa not in (0, 1, 2) or ya not in (0, 1, 2):
                raise ValueError('Unsupported projectile quad alignment')
            left, bottom = (-width*xa/2, -height*(2-ya)/2)
            vertices = []
            for u, v in [(0., 0.), (1., 0.), (1., 1.), (0., 1.)]:
                point = transform_point(matrix, (left+u*width, bottom+v*height, 0.))
                vertices.append([point[0]-moving_pose[3], point[1]-moving_pose[7], u, 1-v])
            lines.append(f'            ProjectileSprite {{ image: include_bytes!("../../../{sprite["image"]}"), key: {q(sprite["image"])}, color: {vector(sprite["color"])}, vertices: [' + ', '.join(vector(vertex) for vertex in vertices) + '] },')
            geometries.append(dict(projectile=item['id'], sprite_component=sprite['path_id'], vertices=vertices))
        lines.extend(['        ],', '    },'])
    lines.append('];')
    attachments = []
    for rig in json.loads((ROOT / 'content/rigs.json').read_text(encoding='utf-8')):
        matches = []
        for pid, (kind, data) in scene.file(rig['source'])[0].items():
            if kind != 114:
                continue
            script = scene.resolve(rig['source'], struct.unpack_from('<iq', data, 16), 115)
            if Reader(script[2]).string() == 'CharacterAssetController':
                matches.append((pid, data))
        item = dict(asset=rig['asset_id'], main_hand=None, off_hand=None, center=None)
        if len(matches) > 1:
            raise ValueError('Ambiguous actor asset controller')
        if matches:
            pid, data = matches[0]
            reader = Reader(data, 28)
            reader.string()
            bone = scene.resolve(rig['source'], reader.unpack('<iq'), 114)
            bone_script = scene.resolve(bone[0], struct.unpack_from('<iq', bone[2], 16), 115)
            if Reader(bone_script[2]).string() != 'BoneAnimation':
                raise ValueError('Unexpected asset-controller base layout')
            for field in ['main_hand', 'off_hand', 'headgear', 'center']:
                pointer = reader.unpack('<iq')
                if not pointer[1]:
                    continue
                target, target_id, _ = scene.resolve(rig['source'], pointer, 4)
                if target != rig['source']:
                    raise ValueError('Actor attachment outside its rig source')
                nodes = [node for node in rig['nodes'] if node['path_id'] == target_id]
                if len(nodes) != 1:
                    raise ValueError('Actor attachment not bound to rig node')
                item[field] = nodes[0]['path']
            item.update(controller_path_id=pid, source=rig['source'], sha256=hashlib.sha256(data).hexdigest())
        attachments.append(item)
    lines.append(f'pub static ATTACHMENTS: [AttachmentDefinition; {len(attachments)}] = [')
    for item in attachments:
        optional = lambda name: 'Some('+q(item[name])+')' if item[name] is not None else 'None'
        lines.append(f'    AttachmentDefinition {{ asset: {q(item["asset"])}, main_hand: {optional("main_hand")}, off_hand: {optional("off_hand")}, center: {optional("center")} }},')
    lines.append('];')
    destination = ROOT / 'crates/epic-client/src/projectiles_generated.rs'
    destination.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    report = dict(source_manifest_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                  projectiles=len(original['projectiles']), static_sprites=len(geometries), geometry=geometries, attachments=attachments,
                  limitations=['Static CHMeshSprite quads only; trails/particles/animated visual clips are not packed.',
                               'Native camera and battle choreography remain unfinished; runtime endpoints use the current battle layout.'])
    (ROOT / 'content/projectile-runtime.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(f'Packed {report["projectiles"]} projectile definitions and {len(geometries)} original static quads')


if __name__ == '__main__':
    build()
