"""Recover original campaign scoring strategies, coefficients and strengths."""
import hashlib
import json

from recover_content import ROOT, describe, load_tables, one, signed_integer


def recover():
    tables, _ = load_tables()
    raw = next(row for row in tables['ScoreBalancingData'] if one(row,1) == b'default_score')
    names = dict(score_per_star=2, full_birds=3, full_pigs=4, loss_per_turn_percent=5,
                 minimum_bird_percent=6, minimum_pig_percent=7, per_strength=8, per_bird=9)
    settings = {name:signed_integer(raw,field) for name,field in names.items()}
    campaign = json.loads((ROOT/'content/campaign.json').read_text())
    original = {one(row,1).decode():row for row in tables['BattleBalancingData']}
    battles = []
    for encounter in campaign['encounters']:
        row = original[encounter['battle_id']]
        strategy = one(row,12,0)
        if strategy not in [0,1]: raise ValueError('Unsupported campaign scoring strategy')
        battles.append(dict(id=encounter['battle_id'],strategy=strategy,bonus=signed_integer(row,13),
                            row_sha256=hashlib.sha256(row).hexdigest()))
    result = dict(settings=settings, score_row_sha256=hashlib.sha256(raw).hexdigest(),
        raw_score_fields=describe(raw), battles=battles,
        pigs=[dict(id=pig['id'],strength=pig['strength']) for pig in campaign['pigs']],
        source_sha256=hashlib.sha256((ROOT/'analysis/unity/balancing.pb').read_bytes()).hexdigest(),
        limitations=['Fixed original campaign waves only; spawned/summoned units, NPC/PvP/banners and special scoring remain unfinished',
            'Score uses current core action-boundary death collection and native round/wave counter mapping; exact coroutine/initiative order and native fractional HP precision still need comparison',
            'Star collection outside the imported main-island encounters remains unfinished'])
    (ROOT/'content/scoring.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    source = ['// Generated by tools/recover_scoring.py.', 'pub const SETTINGS: Settings = Settings {']
    source += [f'    {name}: {value},' for name,value in settings.items()]
    source += ['};','pub const BATTLES: &[Definition] = &[']
    for row in battles:
        source.append(f'    Definition {{ id: {json.dumps(row["id"])}, strategy: {row["strategy"]}, bonus: {row["bonus"]} }},')
    source += ['];','pub const PIG_STRENGTHS: &[i32] = &['+', '.join(str(pig['strength']) for pig in campaign['pigs'])+'];','']
    (ROOT/'crates/epic-core/src/scoring_generated.rs').write_text('\n'.join(source),encoding='utf-8')
    print('Recovered default score coefficients;',len(battles),'campaign strategies;',len(campaign['pigs']),'pig strengths')


if __name__ == '__main__': recover()
