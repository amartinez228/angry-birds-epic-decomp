"""Recover mastery costs, class links, reward scopes and star unlock gate."""
import hashlib
import json
import struct

from recover_content import ROOT, fields, load_tables, one, signed_integer


def recover():
    tables, _ = load_tables()
    costs = []
    for raw in tables['ExperienceMasteryBalancingData']:
        identifier = one(raw, 1).decode()
        rank = int(identifier.removeprefix('Level_'))
        costs.append(dict(id=identifier, rank=rank, cost=signed_integer(raw, 2),
                          stat_bonus_percent=signed_integer(raw, 5), row_sha256=hashlib.sha256(raw).hexdigest()))
    costs.sort(key=lambda row:row['rank'])
    if ([row['rank'] for row in costs] != list(range(1, 101)) or costs[-1]['cost'] != 0
            or any(row['cost'] <= 0 for row in costs[:-1])):
        raise ValueError('Incomplete mastery costs/terminal row')
    catalog = json.loads((ROOT/'content/catalog.json').read_text())
    class_ids = sorted({hat['class_id'] for hat in catalog['hats']})
    original_classes = {one(row,1).decode():row for row in tables['ClassItemBalancingData']}
    classes = []
    for identifier in class_ids:
        raw = original_classes[identifier]
        classes.append(dict(id=identifier, restricted_bird=one(raw,7).decode(), mastery_item=one(raw,14).decode(),
                            row_sha256=hashlib.sha256(raw).hexdigest()))
    items = []
    for raw in tables['MasteryItemBalancingData']:
        def resources(field):
            return [dict(id=one(value,1).decode(), amount=signed_integer(value,2))
                    for number, wire, value in fields(raw) if number == field and wire == 2]
        items.append(dict(id=one(raw,1).decode(), scope=one(raw,7,b'').decode(),
                          fallback=resources(10), fallback_old=resources(11), row_sha256=hashlib.sha256(raw).hexdigest()))
    offer = next(raw for raw in tables['BuyableShopOfferBalancingData'] if one(raw,6,b'') == b'offer_star_reward_02')
    minimum = next(value for field, wire, value in fields(offer)
                   if field == 28 and wire == 2 and one(value,2,b'') == b'star_collection')
    threshold = struct.unpack('<f',one(minimum,3))[0]
    if one(minimum,1) != 2 or threshold != 100.:
        raise ValueError('Unexpected mastery star gate')
    result = dict(costs=costs, classes=classes, items=items, unlock=dict(resource='unlock_mastery_badge',
        offer='offer_star_reward_02', stars=int(threshold), offer_sha256=hashlib.sha256(offer).hexdigest()),
        source_sha256=hashlib.sha256((ROOT/'analysis/unity/balancing.pb').read_bytes()).hexdigest(),
        limitations=['Current-party rewards use the recovered 100-star badge gate and v7 shared class progress; action-boundary delivery/cache refresh approximates native callback timing',
            'Native resource inventory/full star-shop claim flow, non-current reward scopes/fallback, NPC guest ownership, rank-up popup/effects and exact cache callbacks remain unfinished'])
    (ROOT/'content/mastery.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    q = json.dumps
    source = ['// Generated by tools/recover_mastery.py.',
        'pub const COSTS: &[i32; 100] = &['+', '.join(str(row['cost']) for row in costs)+'];',
        f'pub const UNLOCK_STARS: u32 = {int(threshold)};', 'pub const CLASSES: &[ClassDefinition] = &[']
    for row in classes:
        source.append(f'    ClassDefinition {{ id: {q(row["id"])}, restricted_bird: {q(row["restricted_bird"])}, mastery_item: {q(row["mastery_item"])} }},')
    source.extend(['];','pub const ITEMS: &[MasteryItem] = &['])
    for row in items:
        source.append(f'    MasteryItem {{ id: {q(row["id"])}, scope: {q(row["scope"])} }},')
    source.extend(['];',''])
    (ROOT/'crates/epic-core/src/mastery_generated.rs').write_text('\n'.join(source),encoding='utf-8')
    print('Recovered',len(costs),'mastery ranks;',len(classes),'player class links;',len(items),'reward scopes; unlock at',int(threshold),'stars')


if __name__ == '__main__':
    recover()
