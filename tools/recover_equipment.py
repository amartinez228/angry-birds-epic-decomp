"""Import original equipment configuration and fixed default pig loadouts.

Stat coefficients are preserved here; recover_stats.py/stats.rs bind and use
the traced native formulas. Projectile selection is implemented separately.
"""
import hashlib
import json

from recover_content import ROOT, fields, load_tables, one, signed_integer


TEXT = {1: 'id', 3: 'asset_base_id', 4: 'loca_base_id', 12: 'projectile_asset_id',
        14: 'restricted_bird_id', 16: 'corresponding_set_item_id', 19: 'hit_effect_suffix',
        20: 'set_item_skill', 25: 'pvp_set_item_skill'}
INTEGER = {2: 'item_type', 5: 'sort_priority', 6: 'base_stat', 7: 'stat_per_level',
           8: 'stat_per_quality', 10: 'animation_index', 17: 'asset_level_offset',
           18: 'asset_cycle_count', 22: 'main_source'}
BOOLEAN = {11: 'is_ranged', 15: 'direct_asset', 21: 'direct_projectile',
           23: 'show_as_new', 24: 'hide_in_preview'}


def decode(row):
    expected = {**{key: 2 for key in TEXT}, **{key: 0 for key in INTEGER},
                **{key: 0 for key in BOOLEAN}, 9: 0, 13: 2}
    for field, kind, _ in fields(row):
        if expected.get(field) != kind:
            raise ValueError(f'Unsupported equipment field/wire {field}/{kind}')
    result = {name: one(row, field, b'').decode('utf-8') for field, name in TEXT.items()}
    result.update({name: signed_integer(row, field) for field, name in INTEGER.items()})
    for field, name in BOOLEAN.items():
        value = one(row, field, 0)
        if value not in (0, 1):
            raise ValueError('Invalid equipment bool')
        result[name] = bool(value)
    result['stat_per_quality_percent'] = [value for field, _, value in fields(row) if field == 9]
    result['perk_wire_hex'] = one(row, 13, b'').hex()
    result['row_sha256'] = hashlib.sha256(row).hexdigest()
    if not result['id'] or result['item_type'] not in (3, 4):
        raise ValueError('Unsupported equipment identity/item type')
    return result


def recover():
    tables, _ = load_tables()
    equipment = [decode(row) for row in tables['EquipmentBalancingData']]
    indices = {item['id']: index for index, item in enumerate(equipment)}
    if len(indices) != len(equipment):
        raise ValueError('Duplicate equipment ID')
    inventories = {one(row, 1).decode(): row for row in tables['InventoryBalancingData']}
    pigs = json.loads((ROOT / 'content/campaign.json').read_text(encoding='utf-8'))['pigs']
    loadouts = []
    for pig in pigs:
        row = inventories.get(pig['inventory_id'])
        if row is None and pig['inventory_id']:
            raise ValueError('Pig default inventory absent')
        entries = []
        for field, kind, payload in fields(row) if row else []:
            if field != 2:
                continue
            if kind != 2:
                raise ValueError('Unexpected default inventory wire')
            entries.append(dict(id=one(payload, 1).decode(), amount=one(payload, 2, 0)))
        hands = {}
        for item in entries:
            if item['id'] not in indices:
                continue  # Retain class/headgear/other content in the manifest.
            index = indices[item['id']]
            hand = 'main_hand' if equipment[index]['item_type'] == 3 else 'off_hand'
            if hand in hands or item['amount'] != 1:
                raise ValueError('Ambiguous default equipment slot')
            hands[hand] = index
        loadouts.append(dict(pig_id=pig['id'], inventory_id=pig['inventory_id'],
                             inventory_row_sha256=hashlib.sha256(row).hexdigest() if row else None,
                             entries=entries, **hands))
    result = dict(source_container_sha256=hashlib.sha256((ROOT / 'analysis/unity/balancing.pb').read_bytes()).hexdigest(),
                  equipment=equipment, pig_loadouts=loadouts,
                  limitations=['Configuration and deterministic default inventory entries here; stat formulas are in stats.rs. Perks, ownership, loot/crafting and player loadout persistence remain unfinished.'])
    (ROOT / 'content/equipment.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    q = lambda value: json.dumps(value, ensure_ascii=False)
    lines = ['// Generated by tools/recover_equipment.py from supplied balancing data.',
             f'pub static EQUIPMENT: [EquipmentDefinition; {len(equipment)}] = [']
    for item in equipment:
        lines.append('    EquipmentDefinition {')
        for name, value in item.items():
            if name == 'row_sha256':
                continue
            if isinstance(value, str):
                literal = q(value)
            elif isinstance(value, bool):
                literal = str(value).lower()
            elif isinstance(value, list):
                literal = '&[' + ', '.join(map(str, value)) + ']'
            else:
                literal = str(value)
            lines.append(f'        {name}: {literal},')
        lines.append('    },')
    lines.extend(['];', f'pub static PIG_LOADOUTS: [PigLoadout; {len(loadouts)}] = ['])
    for item in loadouts:
        optional = lambda name: f'Some({item[name]})' if name in item else 'None'
        lines.append(f'    PigLoadout {{ pig_id: {q(item["pig_id"])}, main_hand: {optional("main_hand")}, off_hand: {optional("off_hand")} }},')
    lines.append('];')
    (ROOT / 'crates/epic-core/src/equipment_generated.rs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Recovered {len(equipment)} equipment definitions and {len(loadouts)} campaign pig loadouts')


if __name__ == '__main__':
    recover()
